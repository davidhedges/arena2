pub fn reset_player_state_to_spawn(state: &mut PlayerState, now: Timestamp) {
    state.alive = true;
    state.eliminated = false;
    state.hp = state.max_hp;
    state.hit_radius = DEFAULT_HIT_RADIUS;
    state.hit_height = DEFAULT_HIT_HEIGHT;
    state.movement_blocked = false;
    state.move_speed_multiplier = 1.0;
    state.movement_context_tick = 0;
    state.voluntary_move_epoch = 0;
    state.last_voluntary_move_input_tick = 0;
    state.last_strike_id = String::new();
    state.last_strike_at = Timestamp::UNIX_EPOCH;
    mark_respawn_ready(state, now);
}

pub(crate) fn sync_player_state_derived_stats(ctx: &ReducerContext, owner: Identity) -> bool {
    let Some(mut state) = ctx.db.player_state().player_id().find(owner) else {
        return false;
    };
    if state.is_dummy {
        return false;
    }

    let derived = derived_combat_stats_for_owner(ctx, owner);
    let next_max_hp = derived.max_hp.max(1);
    let previous_max_hp = state.max_hp.max(1);
    if previous_max_hp == next_max_hp {
        return false;
    }

    let was_full = state.hp >= previous_max_hp;
    let missing_hp = previous_max_hp.saturating_sub(state.hp.max(0));
    state.max_hp = next_max_hp;
    if was_full {
        state.hp = next_max_hp;
    } else {
        state.hp = next_max_hp.saturating_sub(missing_hp).clamp(0, next_max_hp);
    }

    ctx.db.player_state().player_id().update(state);
    true
}

