pub fn normalize_legacy_hot_status_rows(ctx: &ReducerContext) -> usize {
    let mut repaired = 0_usize;
    let hot_kind = StatusEffectKind::Hot.as_str();
    let hot_rows: Vec<StatusEffect> = ctx
        .db
        .status_effect()
        .effect_kind()
        .filter(hot_kind)
        .collect();

    for mut effect in hot_rows {
        if effect.tick_amount >= 0 {
            continue;
        }
        effect.tick_amount = effect.tick_amount.saturating_abs();
        ctx.db.status_effect().status_id().update(effect);
        repaired += 1;
    }

    repaired
}

// Status expiration is coordinated across three paths:
// 1) `expire_statuses_for_target` pre-cleans a target before stack-policy application.
// 2) `process_periodic_status_ticks` ignores rows that became expired before tick emission.
// 3) `expire_status_effects` runs the indexed sweep to remove any remaining expired rows.
pub fn expire_status_effects(ctx: &ReducerContext, now: Timestamp) {
    // Sweep pass: catches any expired rows not touched by per-target application/tick paths.
    let now_micros = timestamp_to_micros(now);
    ctx.db
        .status_effect()
        .expires_at_micros()
        .delete(..=now_micros);
}

fn expire_statuses_for_target(ctx: &ReducerContext, target: Identity, now: Timestamp) {
    // Pre-application cleanup for target-local status operations.
    let remove_ids: Vec<u64> = ctx
        .db
        .status_effect()
        .target()
        .filter(target)
        .filter(|effect| now >= effect.expires_at)
        .map(|effect| effect.status_id)
        .collect();
    for status_id in remove_ids {
        ctx.db.status_effect().status_id().delete(status_id);
    }
}

pub struct MovementModifiers {
    rooted: HashSet<Identity>,
    disabled: HashSet<Identity>,
    slow_pct_by_target: HashMap<Identity, f32>,
    move_slow_immune: HashSet<Identity>,
}

impl Default for MovementModifiers {
    fn default() -> Self {
        Self {
            rooted: HashSet::new(),
            disabled: HashSet::new(),
            slow_pct_by_target: HashMap::new(),
            move_slow_immune: HashSet::new(),
        }
    }
}

impl MovementModifiers {
    pub fn is_rooted(&self, identity: &Identity) -> bool {
        self.rooted.contains(identity)
    }

    pub fn is_disabled(&self, identity: &Identity) -> bool {
        self.disabled.contains(identity)
    }

    pub fn blocks_movement(&self, identity: &Identity) -> bool {
        self.is_rooted(identity) || self.is_disabled(identity)
    }

    pub fn move_speed_multiplier(&self, identity: &Identity, _input_tick: u32) -> f32 {
        if self.blocks_movement(identity) {
            return 0.0;
        }
        if self.move_slow_immune.contains(identity) {
            return 1.0;
        }
        // Future snares and speed buffs should all resolve into
        // this single derived multiplier so movement prediction only needs one
        // authoritative speed input.
        let slow_pct = self
            .slow_pct_by_target
            .get(identity)
            .copied()
            .unwrap_or(0.0)
            .clamp(0.0, 0.95);
        (1.0 - slow_pct).clamp(0.05, 1.0)
    }
}

#[derive(Clone, Debug)]
struct StatusRuntimeEffect {
    target: Identity,
    kind: StatusEffectKind,
    stack_group: String,
    stacks: u32,
    slow_pct: f32,
    modifier_scalar: f32,
}

impl StatusRuntimeEffect {
    fn from_status_effect(effect: StatusEffect) -> Option<Self> {
        Some(Self {
            target: effect.target,
            kind: StatusEffectKind::from_wire(effect.effect_kind.as_str())?,
            stack_group: effect.stack_group,
            stacks: effect.stacks,
            slow_pct: effect.slow_pct,
            modifier_scalar: effect.modifier_scalar,
        })
    }
}

pub struct StatusRuntimeView {
    effects_by_target: HashMap<Identity, Vec<StatusRuntimeEffect>>,
}

impl StatusRuntimeView {
    pub fn collect(ctx: &ReducerContext, now: Timestamp) -> Self {
        let alive_targets: HashSet<Identity> = ctx
            .db
            .player_state()
            .alive()
            .filter(true)
            .map(|state| state.player_id)
            .collect();

        Self::from_status_effects(ctx.db.status_effect().iter(), &alive_targets, now)
    }

    fn from_status_effects(
        effects: impl IntoIterator<Item = StatusEffect>,
        alive_targets: &HashSet<Identity>,
        now: Timestamp,
    ) -> Self {
        let mut effects_by_target: HashMap<Identity, Vec<StatusRuntimeEffect>> = HashMap::new();

        for effect in effects {
            if now >= effect.expires_at {
                continue;
            }
            if !alive_targets.contains(&effect.target) {
                continue;
            }
            let Some(runtime_effect) = StatusRuntimeEffect::from_status_effect(effect) else {
                continue;
            };
            effects_by_target
                .entry(runtime_effect.target)
                .or_default()
                .push(runtime_effect);
        }

        Self { effects_by_target }
    }

    #[allow(dead_code)]
    pub fn has_status(&self, target: Identity, kind: StatusEffectKind) -> bool {
        self.effects_by_target
            .get(&target)
            .is_some_and(|effects| effects.iter().any(|effect| effect.kind == kind))
    }

    pub fn has_status_group(
        &self,
        target: Identity,
        kind: StatusEffectKind,
        stack_group: &str,
    ) -> bool {
        self.effects_by_target.get(&target).is_some_and(|effects| {
            effects
                .iter()
                .any(|effect| effect.kind == kind && effect.stack_group == stack_group)
        })
    }

    pub fn has_disabling_status(&self, target: Identity) -> bool {
        self.effects_by_target.get(&target).is_some_and(|effects| {
            effects
                .iter()
                .any(|effect| is_hard_crowd_control_kind(effect.kind))
        })
    }

    pub fn movement_modifiers(&self) -> MovementModifiers {
        let mut modifiers = MovementModifiers::default();
        let temporary = self.temporary_combat_modifiers();

        for (target, effects) in self.effects_by_target.iter() {
            if temporary.has_move_slow_immunity(target) {
                modifiers.move_slow_immune.insert(*target);
            }

            for effect in effects {
                match effect.kind {
                    StatusEffectKind::Root => {
                        modifiers.rooted.insert(*target);
                    }
                    StatusEffectKind::Slow => {
                        let entry = modifiers.slow_pct_by_target.entry(*target).or_insert(0.0);
                        *entry = (*entry).max(stacked_slow_pct(effect.slow_pct, effect.stacks));
                    }
                    kind if is_hard_crowd_control_kind(kind) => {
                        modifiers.disabled.insert(*target);
                    }
                    _ => {}
                }
            }
        }

        modifiers
    }

    pub fn temporary_combat_modifiers(&self) -> TemporaryCombatModifiers {
        let mut modifiers = TemporaryCombatModifiers::default();

        for (target, effects) in self.effects_by_target.iter() {
            for effect in effects {
                match effect.kind {
                    StatusEffectKind::MoveSlowImmunity => {
                        modifiers.move_slow_immune.insert(*target);
                    }
                    StatusEffectKind::DamageAmp => {
                        let entry = modifiers.damage_amp_by_target.entry(*target).or_insert(0.0);
                        *entry = (*entry).max(effect.modifier_scalar.max(0.0));
                    }
                    StatusEffectKind::DirectDamageAmp => {
                        let entry = modifiers
                            .direct_damage_amp_by_target
                            .entry(*target)
                            .or_insert(0.0);
                        *entry = (*entry)
                            .max(effect.modifier_scalar.max(0.0) * effect.stacks.max(1) as f32);
                    }
                    StatusEffectKind::HealingTakenReduction => {
                        let entry = modifiers
                            .healing_taken_reduction_by_target
                            .entry(*target)
                            .or_insert(0.0);
                        *entry = (*entry).max(
                            (effect.modifier_scalar.max(0.0) * effect.stacks.max(1) as f32)
                                .clamp(0.0, MAX_HEALING_TAKEN_REDUCTION),
                        );
                    }
                    StatusEffectKind::AttackSpeed => {
                        let entry = modifiers
                            .attack_speed_multiplier_by_target
                            .entry(*target)
                            .or_insert(1.0);
                        *entry *= attack_speed_scalar_to_multiplier(effect.modifier_scalar);
                    }
                    StatusEffectKind::CastSpeed => {
                        let entry = modifiers.cast_speed_by_target.entry(*target).or_insert(0.0);
                        *entry = (*entry).max(effect.modifier_scalar.max(0.0));
                    }
                    StatusEffectKind::Root
                    | StatusEffectKind::Stun
                    | StatusEffectKind::Freeze
                    | StatusEffectKind::Intimidated
                    | StatusEffectKind::Stagger
                    | StatusEffectKind::Knockdown
                    | StatusEffectKind::Slow
                    | StatusEffectKind::Dot
                    | StatusEffectKind::Hot
                    | StatusEffectKind::MeleeAttackModifier
                    | StatusEffectKind::TemporaryHitpoints => {}
                }
            }
        }

        modifiers
    }
}

#[derive(Default)]
pub struct TemporaryCombatModifiers {
    move_slow_immune: HashSet<Identity>,
    damage_amp_by_target: HashMap<Identity, f32>,
    direct_damage_amp_by_target: HashMap<Identity, f32>,
    healing_taken_reduction_by_target: HashMap<Identity, f32>,
    attack_speed_multiplier_by_target: HashMap<Identity, f32>,
    cast_speed_by_target: HashMap<Identity, f32>,
}

impl TemporaryCombatModifiers {
    pub fn has_move_slow_immunity(&self, identity: &Identity) -> bool {
        self.move_slow_immune.contains(identity)
    }

    pub fn damage_multiplier_for(&self, identity: &Identity, delivery: DamageDelivery) -> f32 {
        let base_amp = self
            .damage_amp_by_target
            .get(identity)
            .copied()
            .unwrap_or(0.0)
            .max(0.0);
        let direct_amp = if delivery == DamageDelivery::Direct {
            self.direct_damage_amp_by_target
                .get(identity)
                .copied()
                .unwrap_or(0.0)
                .max(0.0)
        } else {
            0.0
        };
        1.0 + base_amp + direct_amp
    }

    pub fn healing_taken_multiplier_for(&self, identity: &Identity) -> f32 {
        let reduction = self
            .healing_taken_reduction_by_target
            .get(identity)
            .copied()
            .unwrap_or(0.0)
            .clamp(0.0, MAX_HEALING_TAKEN_REDUCTION);
        1.0 - reduction
    }

    #[allow(dead_code)]
    pub fn attack_speed_multiplier_for(&self, identity: &Identity) -> f32 {
        self.attack_speed_multiplier_by_target
            .get(identity)
            .copied()
            .unwrap_or(1.0)
            .max(MIN_ATTACK_SPEED_MULTIPLIER)
    }

    pub fn cast_speed_multiplier_for(&self, identity: &Identity) -> f32 {
        1.0 + self
            .cast_speed_by_target
            .get(identity)
            .copied()
            .unwrap_or(0.0)
            .max(0.0)
    }
}

pub fn process_periodic_status_ticks(ctx: &ReducerContext, now: Timestamp) -> usize {
    let now_micros = timestamp_to_micros(now);
    let mut due_effects: Vec<StatusEffect> = ctx
        .db
        .status_effect()
        .next_tick_at_micros()
        .filter(..=now_micros)
        .collect();
    if due_effects.is_empty() {
        return 0;
    }
    due_effects.sort_by_key(|effect| effect.status_id);
    let alive_targets: HashSet<Identity> = ctx
        .db
        .player_state()
        .alive()
        .filter(true)
        .map(|state| state.player_id)
        .collect();

    let mut queued = Vec::new();

    for mut effect in due_effects {
        // Tick pass skips expired rows; bulk sweep and pre-application paths remove them.
        if effect.tick_interval_ms == 0 || now >= effect.expires_at {
            continue;
        }
        let Some(kind) = StatusEffectKind::from_wire(effect.effect_kind.as_str()) else {
            continue;
        };
        if !matches!(kind, StatusEffectKind::Dot | StatusEffectKind::Hot) {
            continue;
        }
        if !alive_targets.contains(&effect.target) {
            continue;
        }

        let stacks = effect.stacks.max(1) as i32;
        match kind {
            StatusEffectKind::Dot => {
                let base = effect.tick_amount.max(0);
                if base > 0 {
                    queued.push(EffectPacket::Damage {
                        amount: base.saturating_mul(stacks),
                        source: effect.source,
                        target: effect.target,
                        spell_id: effect.spell_id.clone(),
                        delivery: DamageDelivery::Periodic,
                        direct_action_key: String::new(),
                    });
                }
            }
            StatusEffectKind::Hot => {
                let base = effect.tick_amount.max(0);
                if base > 0 {
                    queued.push(EffectPacket::Heal {
                        amount: base.saturating_mul(stacks),
                        source: effect.source,
                        target: effect.target,
                        spell_id: effect.spell_id.clone(),
                        target_audience: TargetAudience::Assistable,
                    });
                }
            }
            _ => {}
        }

        let interval = Duration::from_millis(effect.tick_interval_ms.max(1));
        while effect.next_tick_at <= now {
            effect.next_tick_at += interval;
        }
        let next_tick_at = effect.next_tick_at;
        set_status_next_tick(&mut effect, next_tick_at);
        ctx.db.status_effect().status_id().update(effect);
    }

    if !queued.is_empty() {
        let queued_count = queued.len();
        queue_effects(ctx, queued);
        return queued_count;
    }
    0
}

pub fn movement_modifiers(ctx: &ReducerContext, now: Timestamp) -> MovementModifiers {
    StatusRuntimeView::collect(ctx, now).movement_modifiers()
}

fn stacked_slow_pct(slow_pct: f32, stacks: u32) -> f32 {
    (slow_pct.max(0.0) * stacks.max(1) as f32).clamp(0.0, 0.95)
}

pub fn temporary_combat_modifiers(
    ctx: &ReducerContext,
    now: Timestamp,
) -> TemporaryCombatModifiers {
    StatusRuntimeView::collect(ctx, now).temporary_combat_modifiers()
}

fn attack_speed_scalar_to_multiplier(modifier_scalar: f32) -> f32 {
    if !modifier_scalar.is_finite() {
        return 1.0;
    }

    (1.0 + modifier_scalar).max(MIN_ATTACK_SPEED_MULTIPLIER)
}

