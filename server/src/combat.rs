enum DuePendingEffect {
    Hit(PendingHit),
    ApplyStatus(PendingApplyStatus),
    RemoveStatus(PendingRemoveStatus),
}

#[derive(Default)]
struct PendingEffectStatusCache {
    temporary_modifiers: Option<TemporaryCombatModifiers>,
}

impl PendingEffectStatusCache {
    fn temporary_modifiers(
        &mut self,
        ctx: &ReducerContext,
        now: Timestamp,
    ) -> &TemporaryCombatModifiers {
        if self.temporary_modifiers.is_none() {
            self.temporary_modifiers =
                Some(StatusRuntimeView::collect(ctx, now).temporary_combat_modifiers());
        }

        self.temporary_modifiers
            .as_ref()
            .expect("temporary modifiers should be initialized")
    }

    fn invalidate(&mut self) {
        self.temporary_modifiers = None;
    }
}

impl DuePendingEffect {
    fn sort_key(&self) -> (i64, u8, u64) {
        match self {
            Self::Hit(row) => (row.queued_at_micros, 0, row.queued_order),
            Self::ApplyStatus(row) => (row.queued_at_micros, 0, row.queued_order),
            Self::RemoveStatus(row) => (row.queued_at_micros, 0, row.queued_order),
        }
    }

    fn apply(
        &self,
        ctx: &ReducerContext,
        now: Timestamp,
        status_cache: &mut PendingEffectStatusCache,
    ) {
        match self {
            Self::Hit(row) => {
                let temporary_modifiers = status_cache.temporary_modifiers(ctx, now);
                if row.is_heal {
                    apply_heal(ctx, row, temporary_modifiers);
                } else {
                    if apply_damage(ctx, row, temporary_modifiers) {
                        status_cache.invalidate();
                    }
                }
            }
            Self::ApplyStatus(row) => {
                apply_pending_status_fields(
                    ctx,
                    now,
                    row.source,
                    row.target,
                    row.spell_id.as_str(),
                    row.status_kind.as_str(),
                    row.status_polarity.as_str(),
                    row.duration_ms,
                    row.status_slow_pct,
                    row.status_tick_amount,
                    row.status_tick_interval_ms,
                    row.status_modifier_scalar,
                    row.status_absorb_amount,
                    row.status_absorb_cap,
                    row.stack_group.as_str(),
                    row.max_stacks,
                    row.stack_policy.as_str(),
                    row.target_audience.as_str(),
                );
                status_cache.invalidate();
            }
            Self::RemoveStatus(row) => {
                apply_pending_remove_status_fields(
                    ctx,
                    row.target,
                    row.status_kind.as_str(),
                    row.stack_group.as_str(),
                );
                status_cache.invalidate();
            }
        }
    }

    fn delete(&self, ctx: &ReducerContext) {
        match self {
            Self::Hit(row) => {
                ctx.db.pending_hit().hit_id().delete(row.hit_id);
            }
            Self::ApplyStatus(row) => {
                ctx.db
                    .pending_apply_status()
                    .apply_status_id()
                    .delete(row.apply_status_id);
            }
            Self::RemoveStatus(row) => {
                ctx.db
                    .pending_remove_status()
                    .remove_status_id()
                    .delete(row.remove_status_id);
            }
        }
    }
}

pub fn resolve_pending_effects(ctx: &ReducerContext, now: Timestamp) {
    let now_micros = timestamp_to_micros(now);
    let mut pending: Vec<DuePendingEffect> = Vec::new();

    for row in ctx
        .db
        .pending_hit()
        .queued_at_micros()
        .filter(..=now_micros)
    {
        pending.push(DuePendingEffect::Hit(row));
    }

    for row in ctx
        .db
        .pending_apply_status()
        .queued_at_micros()
        .filter(..=now_micros)
    {
        pending.push(DuePendingEffect::ApplyStatus(row));
    }

    for row in ctx
        .db
        .pending_remove_status()
        .queued_at_micros()
        .filter(..=now_micros)
    {
        pending.push(DuePendingEffect::RemoveStatus(row));
    }

    if pending.is_empty() {
        return;
    }
    pending.sort_by_key(DuePendingEffect::sort_key);

    // HP/status mutations are locked to this pass; spells enqueue only.
    let mut status_cache = PendingEffectStatusCache::default();
    for effect in pending {
        effect.apply(ctx, now, &mut status_cache);
        effect.delete(ctx);
    }
}

pub fn has_due_pending_effects(ctx: &ReducerContext, now: Timestamp) -> bool {
    let now_micros = timestamp_to_micros(now);
    ctx.db
        .pending_hit()
        .queued_at_micros()
        .filter(..=now_micros)
        .next()
        .is_some()
        || ctx
            .db
            .pending_apply_status()
            .queued_at_micros()
            .filter(..=now_micros)
            .next()
            .is_some()
        || ctx
            .db
            .pending_remove_status()
            .queued_at_micros()
            .filter(..=now_micros)
            .next()
            .is_some()
}

#[allow(clippy::too_many_arguments)]
fn apply_pending_status_fields(
    ctx: &ReducerContext,
    now: Timestamp,
    source: Identity,
    target: Identity,
    spell_id: &str,
    status_kind: &str,
    status_polarity: &str,
    duration_ms: u64,
    status_slow_pct: f32,
    status_tick_amount: i32,
    status_tick_interval_ms: u64,
    status_modifier_scalar: f32,
    status_absorb_amount: i32,
    status_absorb_cap: i32,
    stack_group: &str,
    max_stacks: u32,
    stack_policy: &str,
    target_audience: &str,
) {
    let Some(kind) = StatusEffectKind::from_wire(status_kind) else {
        return;
    };
    let Some(polarity) = StatusPolarity::from_wire(status_polarity) else {
        return;
    };
    let Some(stack_policy) = StackPolicy::from_wire(stack_policy) else {
        return;
    };
    let Some(target_audience) = TargetAudience::from_wire(target_audience) else {
        return;
    };

    let payload = StatusPayload::decode(
        kind,
        StatusEffectColumns {
            slow_pct: status_slow_pct,
            tick_amount: status_tick_amount,
            tick_interval_ms: status_tick_interval_ms,
            modifier_scalar: status_modifier_scalar,
            absorb_amount: status_absorb_amount,
            absorb_cap: status_absorb_cap,
        },
    );
    apply_status(
        ctx,
        now,
        source,
        target,
        spell_id,
        payload,
        polarity,
        Duration::from_millis(duration_ms),
        stack_group,
        max_stacks.max(1),
        stack_policy,
        target_audience,
    );
}

fn apply_pending_remove_status_fields(
    ctx: &ReducerContext,
    target: Identity,
    status_kind: &str,
    stack_group: &str,
) {
    let Some(kind) = StatusEffectKind::from_wire(status_kind) else {
        return;
    };
    remove_status_group(ctx, target, kind, stack_group);
}

fn apply_damage(
    ctx: &ReducerContext,
    hit: &PendingHit,
    temporary_modifiers: &TemporaryCombatModifiers,
) -> bool {
    let source = hit.source;
    let target = hit.target;
    if source != Identity::ZERO && !players_share_world_context(ctx, source, target) {
        return false;
    }
    if source != Identity::ZERO && !can_harm(ctx, source, target) {
        return false;
    }

    // PlayerState HP changes happen only here and drive death events below.
    let Some(mut state) = ctx.db.player_state().player_id().find(target) else {
        return false;
    };

    if !state.alive {
        return false;
    }

    let mut resolved = resolve_damage_amount(ctx, hit, temporary_modifiers);
    let resolved_amount = resolved.final_amount;
    if hit.amount > 0 {
        mark_harmful_combat_action(ctx, source, target, ctx.timestamp, COMBAT_REASON_DAMAGE);
    }
    let mut defeated_instance_id = None;
    let hp_damage =
        absorb_damage_with_temporary_hitpoints(ctx, target, resolved_amount, ctx.timestamp);
    resolved.final_amount = hp_damage;
    state.hp -= hp_damage;
    grant_primary_resource_for_damage_taken(ctx, target, hp_damage, ctx.timestamp);
    if state.hp <= 0 {
        state.hp = 0;
        defeated_instance_id = handle_death(ctx, &mut state);
    }

    ctx.db.player_state().player_id().update(state);
    if let Some(instance_id) = defeated_instance_id {
        record_match_kill(ctx, source, instance_id);
        conclude_match_if_needed(ctx, instance_id);
    }
    grant_primary_resource_for_damage_dealt(ctx, source, hp_damage, ctx.timestamp);
    if hp_damage > 0
        && DamageDelivery::from_wire(hit.damage_delivery.as_str()) == DamageDelivery::Direct
    {
        let action_key = if hit.direct_action_key.trim().is_empty() {
            hit.spell_id.as_str()
        } else {
            hit.direct_action_key.as_str()
        };
        record_successful_direct_damage(ctx, source, action_key, ctx.timestamp);
    }
    record_match_damage_done(ctx, source, hp_damage.max(0));
    emit_combat_effect_event(ctx, hit, EFFECT_TYPE_DAMAGE, resolved);
    defeated_instance_id.is_some()
}

fn resolve_damage_amount(
    ctx: &ReducerContext,
    hit: &PendingHit,
    temporary_modifiers: &TemporaryCombatModifiers,
) -> ResolvedEffectAmount {
    let delivery = DamageDelivery::from_wire(hit.damage_delivery.as_str());
    let non_crit_multiplier = if hit.source == Identity::ZERO {
        1.0
    } else {
        temporary_modifiers.damage_multiplier_for(&hit.source, delivery)
            * derived_combat_stats_for_owner(ctx, hit.source).damage_multiplier
    };
    resolve_effect_amount(ctx, hit, non_crit_multiplier)
}

#[derive(Default)]
struct TemporaryHitpointAbsorbResult {
    hp_damage: i32,
    updates: Vec<StatusEffect>,
    delete_ids: Vec<u64>,
}

fn absorb_damage_with_temporary_hitpoints(
    ctx: &ReducerContext,
    target: Identity,
    amount: i32,
    now: Timestamp,
) -> i32 {
    let effects: Vec<StatusEffect> = ctx
        .db
        .status_effect()
        .target()
        .filter(target)
        .filter(|effect| {
            effect.effect_kind == StatusEffectKind::TemporaryHitpoints.as_str()
                && now < effect.expires_at
                && effect.absorb_amount > 0
        })
        .collect();

    let result = resolve_temporary_hitpoint_absorb(effects, amount);
    for effect in result.updates {
        ctx.db.status_effect().status_id().update(effect);
    }
    for status_id in result.delete_ids {
        ctx.db.status_effect().status_id().delete(status_id);
    }

    result.hp_damage
}

fn resolve_temporary_hitpoint_absorb(
    mut effects: Vec<StatusEffect>,
    amount: i32,
) -> TemporaryHitpointAbsorbResult {
    let mut remaining = amount.max(0);
    if remaining == 0 {
        return TemporaryHitpointAbsorbResult {
            hp_damage: 0,
            ..TemporaryHitpointAbsorbResult::default()
        };
    }

    effects.sort_by_key(|effect| (effect.expires_at_micros, effect.status_id));

    let mut updates = Vec::new();
    let mut delete_ids = Vec::new();
    for mut effect in effects {
        if remaining == 0 {
            break;
        }
        let available = effect.absorb_amount.max(0);
        if available == 0 {
            continue;
        }
        let absorbed = available.min(remaining);
        remaining -= absorbed;
        effect.absorb_amount = available - absorbed;
        if effect.absorb_amount == 0 {
            delete_ids.push(effect.status_id);
        } else {
            updates.push(effect);
        }
    }

    TemporaryHitpointAbsorbResult {
        hp_damage: remaining,
        updates,
        delete_ids,
    }
}

fn resolve_heal_amount(
    ctx: &ReducerContext,
    hit: &PendingHit,
    temporary_modifiers: &TemporaryCombatModifiers,
) -> ResolvedEffectAmount {
    let non_crit_multiplier = temporary_modifiers.healing_taken_multiplier_for(&hit.target);
    resolve_effect_amount(ctx, hit, non_crit_multiplier)
}

fn resolve_effect_amount(
    ctx: &ReducerContext,
    hit: &PendingHit,
    non_crit_multiplier: f32,
) -> ResolvedEffectAmount {
    let base_amount = hit.amount.max(0);
    let crit_chance = if hit.source == Identity::ZERO {
        0.0
    } else {
        derived_combat_stats_for_owner(ctx, hit.source)
            .crit_chance
            .clamp(0.0, 1.0)
    };
    resolve_effect_amount_from_roll(
        base_amount,
        hit.source == Identity::ZERO,
        crit_chance,
        stable_hit_roll(hit),
        non_crit_multiplier,
        combat_rule_value(RULE_CRIT_DAMAGE_MULTIPLIER),
    )
}

fn resolve_effect_amount_from_roll(
    base_amount: i32,
    source_is_system: bool,
    crit_chance: f32,
    roll: f32,
    non_crit_multiplier: f32,
    crit_multiplier: f32,
) -> ResolvedEffectAmount {
    let base_amount = base_amount.max(0);
    let crit_chance = if source_is_system {
        0.0
    } else {
        crit_chance.clamp(0.0, 1.0)
    };
    let was_critical = base_amount > 0 && roll < crit_chance;
    let multiplier = non_crit_multiplier.max(0.0)
        * if was_critical {
            crit_multiplier.max(1.0)
        } else {
            1.0
        };
    let final_amount = ((base_amount as f32) * multiplier).round().max(0.0) as i32;

    ResolvedEffectAmount {
        base_amount,
        final_amount,
        was_critical,
        crit_chance,
    }
}

fn emit_combat_effect_event(
    ctx: &ReducerContext,
    hit: &PendingHit,
    effect_type: &str,
    resolved: ResolvedEffectAmount,
) {
    ctx.db.combat_effect_event().insert(CombatEffectEvent {
        event_id: 0,
        spell_id: hit.spell_id.clone(),
        effect_type: effect_type.to_string(),
        source: hit.source,
        target: hit.target,
        base_amount: resolved.base_amount,
        final_amount: resolved.final_amount,
        was_critical: resolved.was_critical,
        crit_chance: resolved.crit_chance,
        created_at: ctx.timestamp,
        created_at_micros: timestamp_to_micros(ctx.timestamp),
    });
}

fn stable_hit_roll(hit: &PendingHit) -> f32 {
    let mut hash = 0xcbf29ce484222325_u64;
    let source_bytes = hit.source.to_byte_array();
    let target_bytes = hit.target.to_byte_array();
    hash = fnv1a_update(hash, &source_bytes);
    hash = fnv1a_update(hash, &target_bytes);
    hash = fnv1a_update(hash, hit.spell_id.as_bytes());
    hash = fnv1a_update(hash, &hit.queued_order.to_le_bytes());
    hash = fnv1a_update(hash, &hit.queued_at_micros.to_le_bytes());
    let bucket = (hash & 0x00ff_ffff) as f32;
    bucket / 16_777_216.0
}

fn fnv1a_update(mut hash: u64, bytes: &[u8]) -> u64 {
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

fn apply_heal(
    ctx: &ReducerContext,
    hit: &PendingHit,
    temporary_modifiers: &TemporaryCombatModifiers,
) {
    let source = hit.source;
    let target = hit.target;
    let amount = hit.amount;
    if amount <= 0 {
        return;
    }
    if source != Identity::ZERO && !players_share_world_context(ctx, source, target) {
        return;
    }
    let target_audience = TargetAudience::from_wire(hit.target_audience.as_str())
        .unwrap_or(TargetAudience::PartyOrSelf);
    if source != Identity::ZERO && !target_audience_allows(ctx, source, target, target_audience) {
        return;
    }

    let Some(mut state) = ctx.db.player_state().player_id().find(target) else {
        return;
    };
    if !state.alive {
        return;
    }

    let resolved = resolve_heal_amount(ctx, hit, temporary_modifiers);
    mark_helpful_combat_assist(ctx, source, target, ctx.timestamp);
    state.hp = (state.hp + resolved.final_amount).min(state.max_hp);
    ctx.db.player_state().player_id().update(state);
    record_match_healing_done(ctx, source, resolved.final_amount);
    emit_combat_effect_event(ctx, hit, EFFECT_TYPE_HEAL, resolved);
}

fn apply_status(
    ctx: &ReducerContext,
    now: Timestamp,
    source: Identity,
    target: Identity,
    spell_id: &str,
    payload: StatusPayload,
    polarity: StatusPolarity,
    duration: Duration,
    stack_group: &str,
    max_stacks: u32,
    stack_policy: StackPolicy,
    target_audience: TargetAudience,
) {
    if duration.is_zero() {
        return;
    }
    let kind = payload.kind();
    if payload.is_invalid() {
        log::warn!(
            "[COMBAT] Rejected invalid status payload kind={} source={} target={} spell_id={}",
            kind.as_str(),
            source.to_hex(),
            target.to_hex(),
            spell_id
        );
        return;
    }

    let Some(state) = ctx.db.player_state().player_id().find(target) else {
        return;
    };
    if !state.alive {
        return;
    }
    if source != Identity::ZERO && !players_share_world_context(ctx, source, target) {
        return;
    }
    if source != Identity::ZERO
        && !can_apply_status_polarity(ctx, source, target, polarity, target_audience)
    {
        return;
    }

    expire_statuses_for_target(ctx, target, now);
    match polarity {
        StatusPolarity::Debuff => {
            mark_harmful_combat_action(ctx, source, target, now, COMBAT_REASON_DEBUFF);
        }
        StatusPolarity::Buff => {
            mark_helpful_combat_assist(ctx, source, target, now);
        }
    }

    let mut matches: Vec<StatusEffect> = ctx
        .db
        .status_effect()
        .target()
        .filter(target)
        .filter(|effect| effect.effect_kind == kind.as_str() && effect.stack_group == stack_group)
        .collect();
    matches.sort_by_key(|effect| effect.status_id);

    let expires_at = now + duration;
    match stack_policy {
        StackPolicy::Refresh => {
            if let Some(mut existing) = matches.into_iter().next() {
                apply_status_update(
                    &mut existing,
                    source,
                    spell_id,
                    polarity,
                    stack_policy,
                    payload,
                    now,
                    expires_at,
                    max_stacks.max(1),
                    Some(1),
                );
                ctx.db.status_effect().status_id().update(existing);
                if kind == StatusEffectKind::Stagger {
                    apply_stagger_status_side_effects(ctx, now, source, target);
                }
                return;
            }
        }
        StackPolicy::AddStackRefresh => {
            if let Some(mut existing) = matches.into_iter().next() {
                let next_stacks = existing.stacks.saturating_add(1).min(max_stacks.max(1));
                apply_status_update(
                    &mut existing,
                    source,
                    spell_id,
                    polarity,
                    stack_policy,
                    payload,
                    now,
                    expires_at,
                    max_stacks.max(1),
                    Some(next_stacks),
                );
                ctx.db.status_effect().status_id().update(existing);
                if kind == StatusEffectKind::Stagger {
                    apply_stagger_status_side_effects(ctx, now, source, target);
                }
                return;
            }
        }
        StackPolicy::ReplaceIfStronger | StackPolicy::IgnoreIfWeaker => {
            if let Some(mut existing) = matches.into_iter().next() {
                if !payload.is_stronger_than_status(&existing) {
                    return;
                }
                apply_status_update(
                    &mut existing,
                    source,
                    spell_id,
                    polarity,
                    stack_policy,
                    payload,
                    now,
                    expires_at,
                    max_stacks.max(1),
                    Some(1),
                );
                ctx.db.status_effect().status_id().update(existing);
                if kind == StatusEffectKind::Stagger {
                    apply_stagger_status_side_effects(ctx, now, source, target);
                }
                return;
            }
        }
    }

    ctx.db.status_effect().insert(new_status_effect(
        target,
        source,
        polarity,
        stack_group,
        max_stacks.max(1),
        stack_policy,
        spell_id,
        payload,
        now,
        expires_at,
    ));
    if kind == StatusEffectKind::Stagger {
        apply_stagger_status_side_effects(ctx, now, source, target);
    }
}

fn apply_stagger_status_side_effects(
    ctx: &ReducerContext,
    now: Timestamp,
    source: Identity,
    target: Identity,
) {
    interrupt_player_actions_for_stagger(ctx, target);
    start_stagger_shove(ctx, now, source, target);
}

pub(crate) fn interrupt_player_actions_for_stagger(ctx: &ReducerContext, target: Identity) {
    let Some(state) = ctx.db.player_state().player_id().find(target) else {
        return;
    };
    if !state.alive {
        return;
    }

    fizzle_active_cast_for_interrupt(ctx, target, ctx.timestamp);
    ctx.db.queued_melee_followup().caster().delete(target);
    ctx.db.defense_state().owner().delete(target);
    ctx.db.movement_action_state().owner().delete(target);
    ctx.db.special_movement_runtime().owner().delete(target);
    ctx.db.pending_melee_timed_movement().owner().delete(target);

    let pending_impact_ids: Vec<u64> = ctx
        .db
        .pending_melee_impact()
        .iter()
        .filter(|row| row.source == target)
        .map(|row| row.impact_id)
        .collect();
    for impact_id in pending_impact_ids {
        ctx.db.pending_melee_impact().impact_id().delete(impact_id);
    }
}

fn stagger_shove_tunables(distance: f32, duration_ms: f32) -> Option<(f32, u64)> {
    let distance = distance.max(0.0);
    let duration_ms = duration_ms.max(0.0).round() as u64;
    if distance <= 0.0 || duration_ms == 0 {
        None
    } else {
        Some((distance, duration_ms))
    }
}

fn yaw_direction(yaw: f32) -> (f32, f32) {
    (yaw.sin(), yaw.cos())
}

fn source_to_target_direction(
    source_physics: Option<&crate::player_physics::PlayerPhysics>,
    target_physics: &crate::player_physics::PlayerPhysics,
) -> (f32, f32) {
    if let Some(source_physics) = source_physics {
        let dx = target_physics.pos_x - source_physics.pos_x;
        let dz = target_physics.pos_z - source_physics.pos_z;
        let len_sq = dx * dx + dz * dz;
        if len_sq > 0.0001 {
            let inv_len = 1.0 / len_sq.sqrt();
            return (dx * inv_len, dz * inv_len);
        }
    }

    yaw_direction(target_physics.yaw)
}

fn start_stagger_shove(ctx: &ReducerContext, now: Timestamp, source: Identity, target: Identity) {
    let Some((distance, duration_ms)) = stagger_shove_tunables(
        combat_rule_value(RULE_STAGGER_SHOVE_DISTANCE_METERS),
        combat_rule_value(RULE_STAGGER_SHOVE_DURATION_MS),
    ) else {
        return;
    };
    let Some(state) = ctx.db.player_state().player_id().find(target) else {
        return;
    };
    if !state.alive {
        return;
    }
    let Some(target_physics) = ctx.db.player_physics().identity().find(target) else {
        return;
    };
    let source_physics = if source == Identity::ZERO {
        None
    } else {
        ctx.db.player_physics().identity().find(source)
    };
    let (dir_x, dir_z) = source_to_target_direction(source_physics.as_ref(), &target_physics);
    let start = SpellVec3::new(
        target_physics.pos_x,
        target_physics.pos_y,
        target_physics.pos_z,
    );
    let intended_end = SpellVec3::new(
        start.x + dir_x * distance,
        start.y,
        start.z + dir_z * distance,
    );
    let baked = bake_linear_special_movement(
        ctx,
        target,
        start,
        intended_end,
        state.hit_radius,
        state.hit_height,
        SPECIAL_MOVEMENT_COLLISION_STOP_AT_BLOCK,
    );
    log::info!(
        "[STAGGER_SHOVE] source={} target={} distance={:.3} duration_ms={} start=({:.3},{:.3},{:.3}) intended_end=({:.3},{:.3},{:.3}) baked_end=({:.3},{:.3},{:.3})",
        source.to_hex(),
        target.to_hex(),
        distance,
        duration_ms,
        start.x,
        start.y,
        start.z,
        intended_end.x,
        intended_end.y,
        intended_end.z,
        baked.end.x,
        baked.end.y,
        baked.end.z
    );
    begin_special_movement_with_facing_policy(
        ctx,
        target,
        STAGGER_SHOVE_KIND,
        now,
        duration_ms,
        start,
        baked.end,
        target_physics.yaw,
        SPECIAL_MOVEMENT_FACING_FACE_START,
        SPECIAL_MOVEMENT_COLLISION_STOP_AT_BLOCK,
    );
}

#[allow(clippy::too_many_arguments)]
fn apply_status_update(
    existing: &mut StatusEffect,
    source: Identity,
    spell_id: &str,
    polarity: StatusPolarity,
    stack_policy: StackPolicy,
    payload: StatusPayload,
    now: Timestamp,
    expires_at: Timestamp,
    max_stacks: u32,
    stacks_override: Option<u32>,
) {
    let mut columns = payload.encode();
    if matches!(payload, StatusPayload::TemporaryHitpoints { .. }) {
        match stack_policy {
            StackPolicy::AddStackRefresh => {
                columns.absorb_amount = existing
                    .absorb_amount
                    .max(0)
                    .saturating_add(columns.absorb_amount.max(0))
                    .min(columns.absorb_cap.max(0));
            }
            _ => {
                columns.absorb_amount = columns.absorb_amount.min(columns.absorb_cap.max(0));
            }
        }
    }

    existing.source = source;
    existing.polarity = polarity.as_str().to_string();
    existing.applied_at = now;
    set_status_expires_at(existing, expires_at);
    existing.max_stacks = max_stacks.max(1);
    existing.stack_policy = stack_policy.as_str().to_string();
    existing.spell_id = spell_id.to_string();
    existing.slow_pct = columns.slow_pct;
    existing.tick_amount = columns.tick_amount;
    existing.tick_interval_ms = columns.tick_interval_ms;
    existing.modifier_scalar = columns.modifier_scalar;
    existing.absorb_amount = columns.absorb_amount;
    existing.absorb_cap = columns.absorb_cap;
    set_status_next_tick(existing, next_status_tick(now, columns.tick_interval_ms));
    if let Some(stacks) = stacks_override {
        existing.stacks = stacks.min(existing.max_stacks).max(1);
    }
}

