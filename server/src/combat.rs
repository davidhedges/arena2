#[derive(Clone, Debug, PartialEq)]
pub struct StatusApplication {
    payload: StatusPayload,
    duration: Duration,
    status_stack_group: Option<String>,
    stack_group_default: StatusStackGroupDefault,
    max_stacks: u32,
    stack_policy: StackPolicy,
}

impl StatusApplication {
    pub fn new(
        payload: StatusPayload,
        duration: Duration,
        status_stack_group: Option<String>,
        stack_group_default: StatusStackGroupDefault,
        max_stacks: u32,
        stack_policy: StackPolicy,
    ) -> Self {
        Self {
            payload,
            duration,
            status_stack_group,
            stack_group_default,
            max_stacks,
            stack_policy,
        }
    }

    pub fn payload(&self) -> StatusPayload {
        self.payload
    }

    pub fn duration(&self) -> Duration {
        self.duration
    }

    pub fn explicit_stack_group(&self) -> Option<&str> {
        self.status_stack_group.as_deref()
    }

    pub fn max_stacks(&self) -> u32 {
        self.max_stacks.max(1)
    }

    pub fn authored_max_stacks(&self) -> u32 {
        self.max_stacks
    }

    pub fn stack_policy(&self) -> StackPolicy {
        self.stack_policy
    }

    pub fn requires_positive_damage(&self) -> bool {
        matches!(self.payload, StatusPayload::Stagger)
    }

    pub fn is_invalid(&self) -> bool {
        self.duration.is_zero()
            || self.payload.is_invalid()
            || self.max_stacks == 0
            || self
                .status_stack_group
                .as_deref()
                .is_some_and(|stack_group| stack_group.trim().is_empty())
    }

    pub fn stack_group(&self, action_key: &str, instance_id: &str) -> String {
        match self.stack_group_default {
            StatusStackGroupDefault::EffectKind => self
                .status_stack_group
                .clone()
                .unwrap_or_else(|| self.payload.kind().as_str().to_string()),
            StatusStackGroupDefault::ActionSuffix(suffix) => self
                .status_stack_group
                .clone()
                .unwrap_or_else(|| format!("{action_key}_{suffix}")),
            StatusStackGroupDefault::Global(group) => self
                .status_stack_group
                .clone()
                .unwrap_or_else(|| group.to_string()),
            StatusStackGroupDefault::InstanceScopedActionSuffix(suffix) => {
                let base = self
                    .status_stack_group
                    .clone()
                    .unwrap_or_else(|| format!("{action_key}_{suffix}"));
                format!("{base}:{instance_id}")
            }
        }
    }

    pub fn to_effect_packet(
        &self,
        source: Identity,
        target: Identity,
        spell_id: &str,
        polarity: StatusPolarity,
        action_key: &str,
    ) -> EffectPacket {
        let target_audience = match polarity {
            StatusPolarity::Debuff => TargetAudience::Hostile,
            StatusPolarity::Buff => TargetAudience::PartyOrSelf,
        };
        self.to_effect_packet_for_audience(
            source,
            target,
            spell_id,
            polarity,
            target_audience,
            action_key,
        )
    }

    pub fn to_effect_packet_for_audience(
        &self,
        source: Identity,
        target: Identity,
        spell_id: &str,
        polarity: StatusPolarity,
        target_audience: TargetAudience,
        action_key: &str,
    ) -> EffectPacket {
        EffectPacket::ApplyStatus {
            source,
            target,
            spell_id: spell_id.to_string(),
            payload: self.payload(),
            polarity,
            target_audience,
            duration: self.duration(),
            stack_group: self.stack_group(action_key, spell_id),
            max_stacks: self.max_stacks(),
            stack_policy: self.stack_policy(),
        }
    }
}

