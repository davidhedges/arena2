pub(crate) fn sync_combat_projectile_definitions(ctx: &ReducerContext) {
    let expected: HashSet<_> = COMBAT_PROJECTILE_DEFINITIONS
        .iter()
        .map(|definition| definition.projectile_id.to_string())
        .collect();

    for definition in COMBAT_PROJECTILE_DEFINITIONS {
        let row = CombatProjectileDefinition {
            projectile_id: definition.projectile_id.to_string(),
            speed: definition.speed,
            max_distance: definition.max_distance,
            radius: definition.radius,
            spawn_forward: definition.spawn_forward,
            spawn_height: definition.spawn_height,
            aim_height_scale: definition.aim_height_scale,
            requires_initial_line_of_sight: definition.requires_initial_line_of_sight,
            update_interval_seconds: definition.update_interval_seconds,
        };
        if ctx
            .db
            .combat_projectile_definition()
            .projectile_id()
            .find(row.projectile_id.clone())
            .is_some()
        {
            ctx.db
                .combat_projectile_definition()
                .projectile_id()
                .update(row);
        } else {
            ctx.db.combat_projectile_definition().insert(row);
        }
    }

    let stale: Vec<_> = ctx
        .db
        .combat_projectile_definition()
        .iter()
        .map(|row| row.projectile_id)
        .filter(|projectile_id| !expected.contains(projectile_id))
        .collect();
    for projectile_id in stale {
        ctx.db
            .combat_projectile_definition()
            .projectile_id()
            .delete(projectile_id);
    }
}

