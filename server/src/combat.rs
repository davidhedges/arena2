fn physics_position_or_default(ctx: &ReducerContext, player_id: Identity) -> (f32, f32, f32) {
    if let Some(physics) = ctx.db.player_physics().identity().find(player_id) {
        (physics.pos_x, physics.pos_y, physics.pos_z)
    } else {
        (0.0, 0.0, 0.0)
    }
}

fn handle_death(ctx: &ReducerContext, state: &mut PlayerState) -> Option<u64> {
    if !state.alive {
        return None;
    }

    let arena_match_instance = ctx
        .db
        .player_world()
        .identity()
        .find(state.player_id)
        .and_then(|world| world.instance_id)
        .filter(|instance_id| is_live_arena_match(ctx, *instance_id));

    state.alive = false;
    state.eliminated = arena_match_instance.is_some();
    if state.eliminated {
        mark_respawn_ready(state, ctx.timestamp);
    } else {
        mark_respawn_pending(state, ctx.timestamp);
    }
    clear_statuses_for_target(ctx, state.player_id);
    clear_combat_engagement_for_identity(ctx, state.player_id);
    clear_combat_stacking_passive_runtime_for_identity(ctx, state.player_id);

    let (event_x, event_y, event_z) = physics_position_or_default(ctx, state.player_id);

    emit_player_event(
        ctx,
        EVENT_PLAYER_DIED,
        state.player_id,
        event_x,
        event_y,
        event_z,
        ctx.timestamp,
    );

    arena_match_instance
}

pub fn respawn_player(ctx: &ReducerContext, state: &mut PlayerState) -> (f32, f32, f32, f32) {
    let (spawn_x, spawn_y, spawn_z, spawn_yaw) =
        resolve_respawn_pose(ctx, state.player_id, state.hit_radius, state.hit_height)
            .unwrap_or_else(|| {
                let arena_seed = arena_seed_for_identity(ctx, state.player_id);
                let profile = open_world_scene_profile_for_identity(ctx, state.player_id);
                let (desired_x, desired_z, yaw, scene_name) = if arena_seed.is_some() {
                    (SPAWN_X, SPAWN_Z, OPEN_WORLD_SPAWN_YAW, None)
                } else {
                    (
                        profile.spawn_x,
                        profile.spawn_z,
                        profile.spawn_yaw,
                        Some(profile.scene_name),
                    )
                };
                let (spawn_x, spawn_y, spawn_z) =
                    resolve_world_spawn_position_with_layout_for_scene(
                        arena_seed,
                        false,
                        scene_name,
                        desired_x,
                        desired_z,
                        state.hit_radius.max(0.1),
                        state.hit_height.max(0.5),
                    );
                (spawn_x, spawn_y, spawn_z, yaw)
            });

    reset_player_state_to_spawn(state, ctx.timestamp);
    clear_statuses_for_target(ctx, state.player_id);
    clear_combat_engagement_for_identity(ctx, state.player_id);
    clear_combat_stacking_passive_runtime_for_identity(ctx, state.player_id);

    emit_player_event(
        ctx,
        EVENT_PLAYER_RESPAWNED,
        state.player_id,
        spawn_x,
        spawn_y,
        spawn_z,
        ctx.timestamp,
    );

    (spawn_x, spawn_y, spawn_z, spawn_yaw)
}

fn is_live_arena_match(ctx: &ReducerContext, instance_id: u64) -> bool {
    let Some(instance) = ctx.db.arena_instance().id().find(instance_id) else {
        return false;
    };

    if instance.is_practice || is_training_instance(ctx, instance_id) {
        return false;
    }

    instance.phase == MATCH_PHASE_IN_PROGRESS
}

fn count_alive_non_eliminated_in_instance(ctx: &ReducerContext, instance_id: u64) -> usize {
    ctx.db
        .player_world()
        .iter()
        .filter(|world| world.instance_id == Some(instance_id))
        .filter_map(|world| ctx.db.player_state().player_id().find(world.identity))
        .filter(|state| state.alive && !state.eliminated)
        .count()
}

fn last_alive_non_eliminated_in_instance(
    ctx: &ReducerContext,
    instance_id: u64,
) -> Option<Identity> {
    ctx.db
        .player_world()
        .iter()
        .filter(|world| world.instance_id == Some(instance_id))
        .find_map(|world| {
            let state = ctx.db.player_state().player_id().find(world.identity)?;
            if state.alive && !state.eliminated {
                Some(world.identity)
            } else {
                None
            }
        })
}

fn conclude_match_if_needed(ctx: &ReducerContext, instance_id: u64) {
    if count_alive_non_eliminated_in_instance(ctx, instance_id) > 1 {
        return;
    }

    let Some(mut instance) = ctx.db.arena_instance().id().find(instance_id) else {
        return;
    };

    if instance.phase == MATCH_PHASE_ENDED {
        return;
    }

    instance.phase = MATCH_PHASE_ENDED.to_string();
    instance.winner_id = last_alive_non_eliminated_in_instance(ctx, instance_id);
    instance.ended_at = Some(ctx.timestamp);
    ctx.db.arena_instance().id().update(instance);
    snapshot_match_hp_remaining(ctx, instance_id);
}

fn snapshot_match_hp_remaining(ctx: &ReducerContext, instance_id: u64) {
    let participants: Vec<(Identity, i32)> = ctx
        .db
        .player_world()
        .iter()
        .filter(|world| world.instance_id == Some(instance_id))
        .filter_map(|world| {
            let state = ctx.db.player_state().player_id().find(world.identity)?;
            Some((world.identity, state.hp.max(0)))
        })
        .collect();

    for (identity, hp) in participants {
        let key = format!("{instance_id}:{}", identity.to_hex());
        if let Some(mut stats) = ctx.db.match_participant_stats().key().find(key.clone()) {
            stats.hp_remaining = hp;
            ctx.db.match_participant_stats().key().update(stats);
        } else {
            ctx.db
                .match_participant_stats()
                .insert(MatchParticipantStats {
                    key,
                    instance_id,
                    player_id: identity,
                    damage_done: 0,
                    healing_done: 0,
                    kills: 0,
                    hp_remaining: hp,
                });
        }
    }
}

fn record_match_damage_done(ctx: &ReducerContext, source: Identity, amount: i32) {
    if amount <= 0 {
        return;
    }
    record_match_stats_delta(ctx, source, amount, 0);
}

fn record_match_healing_done(ctx: &ReducerContext, source: Identity, amount: i32) {
    if amount <= 0 {
        return;
    }
    record_match_stats_delta(ctx, source, 0, amount);
}

fn record_match_stats_delta(
    ctx: &ReducerContext,
    source: Identity,
    damage_delta: i32,
    healing_delta: i32,
) {
    if source == Identity::ZERO {
        return;
    }

    let Some(world) = ctx.db.player_world().identity().find(source) else {
        return;
    };
    let Some(instance_id) = world.instance_id else {
        return;
    };
    let Some(instance) = ctx.db.arena_instance().id().find(instance_id) else {
        return;
    };
    if instance.is_practice {
        return;
    }

    let key = format!("{instance_id}:{}", source.to_hex());
    if let Some(mut stats) = ctx.db.match_participant_stats().key().find(key.clone()) {
        stats.damage_done = stats.damage_done.saturating_add(damage_delta.max(0));
        stats.healing_done = stats.healing_done.saturating_add(healing_delta.max(0));
        ctx.db.match_participant_stats().key().update(stats);
        return;
    }

    ctx.db
        .match_participant_stats()
        .insert(MatchParticipantStats {
            key,
            instance_id,
            player_id: source,
            damage_done: damage_delta.max(0),
            healing_done: healing_delta.max(0),
            kills: 0,
            hp_remaining: 0,
        });
}

fn record_match_kill(ctx: &ReducerContext, killer: Identity, instance_id: u64) {
    if killer == Identity::ZERO {
        return;
    }
    let key = format!("{instance_id}:{}", killer.to_hex());
    if let Some(mut stats) = ctx.db.match_participant_stats().key().find(key.clone()) {
        stats.kills = stats.kills.saturating_add(1);
        ctx.db.match_participant_stats().key().update(stats);
    } else {
        ctx.db
            .match_participant_stats()
            .insert(MatchParticipantStats {
                key,
                instance_id,
                player_id: killer,
                damage_done: 0,
                healing_done: 0,
                kills: 1,
                hp_remaining: 0,
            });
    }
}

