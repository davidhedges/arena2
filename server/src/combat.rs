pub fn is_in_combat(ctx: &ReducerContext, owner: Identity, now: Timestamp) -> bool {
    ctx.db
        .combat_engagement()
        .owner()
        .find(owner)
        .is_some_and(|row| now < row.expires_at)
}

pub fn mark_harmful_combat_action(
    ctx: &ReducerContext,
    source: Identity,
    target: Identity,
    now: Timestamp,
    reason: &str,
) {
    if source == Identity::ZERO || target == Identity::ZERO || source == target {
        return;
    }
    if !players_share_world_context(ctx, source, target) {
        return;
    }

    mark_identity_in_combat(ctx, source, now, reason, source, target);
    mark_identity_in_combat(ctx, target, now, reason, source, target);
}

fn mark_helpful_combat_assist(
    ctx: &ReducerContext,
    source: Identity,
    target: Identity,
    now: Timestamp,
) {
    if source == Identity::ZERO || target == Identity::ZERO || source == target {
        return;
    }
    if !players_share_world_context(ctx, source, target) {
        return;
    }
    if !is_in_combat(ctx, target, now) {
        return;
    }

    mark_identity_in_combat(
        ctx,
        source,
        now,
        COMBAT_REASON_HELPFUL_ASSIST,
        source,
        target,
    );
}

fn mark_identity_in_combat(
    ctx: &ReducerContext,
    owner: Identity,
    now: Timestamp,
    reason: &str,
    source: Identity,
    target: Identity,
) {
    if owner == Identity::ZERO {
        return;
    }
    let Some(state) = ctx.db.player_state().player_id().find(owner) else {
        return;
    };
    if !state.alive {
        return;
    }

    let requested_expires_at = now + DEFAULT_COMBAT_ENGAGEMENT_DURATION;
    let requested_expires_at_micros = timestamp_to_micros(requested_expires_at);
    if let Some(mut row) = ctx.db.combat_engagement().owner().find(owner) {
        if now >= row.expires_at {
            row.entered_at = now;
        }
        row.last_activity_at = now;
        if requested_expires_at > row.expires_at {
            row.expires_at = requested_expires_at;
            row.expires_at_micros = requested_expires_at_micros;
        }
        row.reason = reason.to_string();
        row.source = source;
        row.target = target;
        ctx.db.combat_engagement().owner().update(row);
    } else {
        ctx.db.combat_engagement().insert(CombatEngagement {
            owner,
            entered_at: now,
            last_activity_at: now,
            expires_at: requested_expires_at,
            expires_at_micros: requested_expires_at_micros,
            reason: reason.to_string(),
            source,
            target,
        });
    }
}

pub fn expire_combat_engagements(ctx: &ReducerContext, now: Timestamp) {
    ctx.db
        .combat_engagement()
        .expires_at_micros()
        .delete(..=timestamp_to_micros(now));
}

pub fn clear_combat_engagement_for_identity(ctx: &ReducerContext, identity: Identity) {
    if ctx.db.combat_engagement().owner().find(identity).is_some() {
        ctx.db.combat_engagement().owner().delete(identity);
    }
}

struct CombatStackingPassiveSpec {
    passive_id: &'static str,
    class_id: &'static str,
    stack_group: &'static str,
    status_kind: StatusEffectKind,
    max_stacks: u32,
    gain_delay: Duration,
    gain_interval: Duration,
    out_of_combat_decay_interval: Duration,
    consume_on_direct_damage: u32,
    damage_amp_per_stack: f32,
}

fn restless_passive_spec() -> CombatStackingPassiveSpec {
    CombatStackingPassiveSpec {
        passive_id: RESTLESS_PASSIVE_ID,
        class_id: WARRIOR_CLASS_ID,
        stack_group: RESTLESS_PASSIVE_ID,
        status_kind: StatusEffectKind::DirectDamageAmp,
        max_stacks: 50,
        gain_delay: Duration::from_secs(4),
        gain_interval: Duration::from_secs(1),
        out_of_combat_decay_interval: Duration::from_millis(500),
        consume_on_direct_damage: 10,
        damage_amp_per_stack: 0.02,
    }
}

pub fn tick_combat_stacking_passives(ctx: &ReducerContext, now: Timestamp) {
    let spec = restless_passive_spec();
    let mut owners: HashSet<Identity> = ctx
        .db
        .player_state()
        .iter()
        .map(|state| state.player_id)
        .collect();
    owners.extend(
        ctx.db
            .combat_stacking_passive_runtime()
            .iter()
            .map(|row| row.owner),
    );
    owners.extend(
        ctx.db
            .status_effect()
            .effect_kind()
            .filter(spec.status_kind.as_str())
            .filter(|effect| effect.stack_group == spec.stack_group)
            .map(|effect| effect.target),
    );

    for owner in owners {
        tick_combat_stacking_passive_for_owner(ctx, owner, &spec, now);
    }
}

fn tick_combat_stacking_passive_for_owner(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
    now: Timestamp,
) {
    let alive = ctx
        .db
        .player_state()
        .player_id()
        .find(owner)
        .is_some_and(|state| state.alive);
    if !alive || !combat_stacking_passive_eligible(ctx, owner, spec) {
        clear_combat_stacking_passive(ctx, owner, spec);
        return;
    }

    if is_in_combat(ctx, owner, now) {
        tick_combat_stacking_passive_in_combat(ctx, owner, spec, now);
    } else {
        tick_combat_stacking_passive_out_of_combat(ctx, owner, spec, now);
    }
}

fn tick_combat_stacking_passive_in_combat(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
    now: Timestamp,
) {
    let key = combat_stacking_passive_runtime_key(owner, spec.passive_id);
    let combat_entered_at = ctx
        .db
        .combat_engagement()
        .owner()
        .find(owner)
        .map(|row| row.entered_at)
        .unwrap_or(now);
    let minimum_next_stack_at = combat_entered_at + spec.gain_delay;
    let mut runtime = if let Some(mut existing) = ctx
        .db
        .combat_stacking_passive_runtime()
        .key()
        .find(key.clone())
    {
        if existing.next_stack_at < minimum_next_stack_at {
            existing.next_stack_at = minimum_next_stack_at;
        }
        existing
    } else {
        CombatStackingPassiveRuntime {
            key,
            owner,
            passive_id: spec.passive_id.to_string(),
            next_stack_at: minimum_next_stack_at,
            last_direct_damage_at: Timestamp::UNIX_EPOCH,
            last_consumed_action_key: String::new(),
        }
    };

    let due = due_interval_count(now, runtime.next_stack_at, spec.gain_interval);
    if due > 0 {
        let stacks = combat_stacking_passive_stacks(ctx, owner, spec);
        let next_stacks = stacks.saturating_add(due).min(spec.max_stacks);
        set_combat_stacking_passive_stacks(ctx, owner, spec, next_stacks, now);
        runtime.next_stack_at =
            advance_timestamp_by_intervals(runtime.next_stack_at, spec.gain_interval, due);
    }
    upsert_combat_stacking_passive_runtime(ctx, runtime);
}

fn tick_combat_stacking_passive_out_of_combat(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
    now: Timestamp,
) {
    let stacks = combat_stacking_passive_stacks(ctx, owner, spec);
    if stacks == 0 {
        clear_combat_stacking_passive_runtime(ctx, owner, spec.passive_id);
        return;
    }

    let key = combat_stacking_passive_runtime_key(owner, spec.passive_id);
    let mut runtime = if let Some(existing) = ctx
        .db
        .combat_stacking_passive_runtime()
        .key()
        .find(key.clone())
    {
        existing
    } else {
        CombatStackingPassiveRuntime {
            key,
            owner,
            passive_id: spec.passive_id.to_string(),
            next_stack_at: now + spec.out_of_combat_decay_interval,
            last_direct_damage_at: Timestamp::UNIX_EPOCH,
            last_consumed_action_key: String::new(),
        }
    };

    let next_decay_cap = now + spec.out_of_combat_decay_interval;
    if runtime.next_stack_at > next_decay_cap {
        runtime.next_stack_at = next_decay_cap;
        upsert_combat_stacking_passive_runtime(ctx, runtime);
        return;
    }

    let due = due_interval_count(
        now,
        runtime.next_stack_at,
        spec.out_of_combat_decay_interval,
    );
    if due == 0 {
        upsert_combat_stacking_passive_runtime(ctx, runtime);
        return;
    }

    let next_stacks = stacks.saturating_sub(due);
    if next_stacks == 0 {
        clear_combat_stacking_passive(ctx, owner, spec);
        return;
    }

    set_combat_stacking_passive_stacks(ctx, owner, spec, next_stacks, now);
    runtime.next_stack_at = advance_timestamp_by_intervals(
        runtime.next_stack_at,
        spec.out_of_combat_decay_interval,
        due,
    );
    upsert_combat_stacking_passive_runtime(ctx, runtime);
}

fn record_successful_direct_damage(
    ctx: &ReducerContext,
    source: Identity,
    direct_action_key: &str,
    now: Timestamp,
) {
    if source == Identity::ZERO {
        return;
    }

    let spec = restless_passive_spec();
    if !combat_stacking_passive_eligible(ctx, source, &spec) {
        return;
    }

    let action_key = direct_action_key.trim();
    if action_key.is_empty() {
        return;
    }

    let key = combat_stacking_passive_runtime_key(source, spec.passive_id);
    let mut runtime = if let Some(existing) = ctx
        .db
        .combat_stacking_passive_runtime()
        .key()
        .find(key.clone())
    {
        existing
    } else {
        CombatStackingPassiveRuntime {
            key,
            owner: source,
            passive_id: spec.passive_id.to_string(),
            next_stack_at: now + spec.gain_delay,
            last_direct_damage_at: Timestamp::UNIX_EPOCH,
            last_consumed_action_key: String::new(),
        }
    };

    if runtime.last_consumed_action_key == action_key {
        return;
    }

    runtime.last_direct_damage_at = now;
    runtime.next_stack_at = now + spec.gain_delay;
    runtime.last_consumed_action_key = action_key.to_string();
    upsert_combat_stacking_passive_runtime(ctx, runtime);

    let stacks = combat_stacking_passive_stacks(ctx, source, &spec);
    if stacks == 0 {
        return;
    }
    let next_stacks = stacks.saturating_sub(spec.consume_on_direct_damage);
    set_combat_stacking_passive_stacks(ctx, source, &spec, next_stacks, now);
}

fn combat_stacking_passive_eligible(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
) -> bool {
    runtime_class_id_for_owner(ctx, owner).is_some_and(|class_id| class_id == spec.class_id)
}

fn combat_stacking_passive_stacks(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
) -> u32 {
    combat_stacking_passive_status(ctx, owner, spec)
        .map(|effect| effect.stacks.min(effect.max_stacks).min(spec.max_stacks))
        .unwrap_or(0)
}

fn combat_stacking_passive_status(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
) -> Option<StatusEffect> {
    let mut matches: Vec<StatusEffect> = ctx
        .db
        .status_effect()
        .target()
        .filter(owner)
        .filter(|effect| {
            effect.effect_kind == spec.status_kind.as_str()
                && effect.stack_group == spec.stack_group
        })
        .collect();
    matches.sort_by_key(|effect| effect.status_id);
    matches.into_iter().next()
}

fn set_combat_stacking_passive_stacks(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
    stacks: u32,
    now: Timestamp,
) {
    let stacks = stacks.min(spec.max_stacks);
    if stacks == 0 {
        remove_status_group(ctx, owner, spec.status_kind, spec.stack_group);
        return;
    }

    let expires_at = now + PASSIVE_STATUS_REFRESH_DURATION;
    let payload = StatusPayload::DirectDamageAmp {
        modifier_scalar: spec.damage_amp_per_stack,
    };
    if let Some(mut existing) = combat_stacking_passive_status(ctx, owner, spec) {
        apply_status_update(
            &mut existing,
            owner,
            spec.passive_id,
            StatusPolarity::Buff,
            StackPolicy::Refresh,
            payload,
            now,
            expires_at,
            spec.max_stacks,
            Some(stacks),
        );
        ctx.db.status_effect().status_id().update(existing);
    } else {
        let mut effect = new_status_effect(
            owner,
            owner,
            StatusPolarity::Buff,
            spec.stack_group,
            spec.max_stacks,
            StackPolicy::Refresh,
            spec.passive_id,
            payload,
            now,
            expires_at,
        );
        effect.stacks = stacks;
        ctx.db.status_effect().insert(effect);
    }
}

fn clear_combat_stacking_passive(
    ctx: &ReducerContext,
    owner: Identity,
    spec: &CombatStackingPassiveSpec,
) {
    remove_status_group(ctx, owner, spec.status_kind, spec.stack_group);
    clear_combat_stacking_passive_runtime(ctx, owner, spec.passive_id);
}

fn clear_combat_stacking_passive_runtime(ctx: &ReducerContext, owner: Identity, passive_id: &str) {
    let key = combat_stacking_passive_runtime_key(owner, passive_id);
    if ctx
        .db
        .combat_stacking_passive_runtime()
        .key()
        .find(key.clone())
        .is_some()
    {
        ctx.db.combat_stacking_passive_runtime().key().delete(key);
    }
}

fn clear_combat_stacking_passive_runtime_for_identity(ctx: &ReducerContext, owner: Identity) {
    let keys: Vec<String> = ctx
        .db
        .combat_stacking_passive_runtime()
        .owner()
        .filter(owner)
        .map(|row| row.key)
        .collect();
    for key in keys {
        ctx.db.combat_stacking_passive_runtime().key().delete(key);
    }
}

fn upsert_combat_stacking_passive_runtime(
    ctx: &ReducerContext,
    runtime: CombatStackingPassiveRuntime,
) {
    if ctx
        .db
        .combat_stacking_passive_runtime()
        .key()
        .find(runtime.key.clone())
        .is_some()
    {
        ctx.db
            .combat_stacking_passive_runtime()
            .key()
            .update(runtime);
    } else {
        ctx.db.combat_stacking_passive_runtime().insert(runtime);
    }
}

fn combat_stacking_passive_runtime_key(owner: Identity, passive_id: &str) -> String {
    format!("{}:{}", owner.to_hex(), passive_id)
}

fn due_interval_count(now: Timestamp, next_at: Timestamp, interval: Duration) -> u32 {
    if now < next_at {
        return 0;
    }
    let interval_micros = duration_micros(interval);
    let elapsed = (timestamp_to_micros(now) - timestamp_to_micros(next_at)).max(0);
    1_u32.saturating_add((elapsed / interval_micros) as u32)
}

fn advance_timestamp_by_intervals(
    timestamp: Timestamp,
    interval: Duration,
    intervals: u32,
) -> Timestamp {
    Timestamp::from_micros_since_unix_epoch(
        timestamp_to_micros(timestamp)
            .saturating_add(duration_micros(interval).saturating_mul(intervals as i64)),
    )
}

fn duration_micros(duration: Duration) -> i64 {
    (duration.as_micros().max(1).min(i64::MAX as u128)) as i64
}

