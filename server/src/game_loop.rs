fn try_tick_dead_player(
    ctx: &ReducerContext,
    now: Timestamp,
    physics: &mut PlayerPhysics,
    state: &mut crate::player_state::PlayerState,
) -> bool {
    if state.alive {
        return false;
    }

    if state.eliminated {
        return true;
    }

    if now >= state.respawn_at {
        let (spawn_x, spawn_y, spawn_z, spawn_yaw) = respawn_player(ctx, state);
        physics.pos_x = spawn_x;
        physics.pos_y = spawn_y;
        physics.pos_z = spawn_z;
        physics.vel_x = 0.0;
        physics.vel_y = 0.0;
        physics.vel_z = 0.0;
        physics.yaw = spawn_yaw;
        physics.grounded = true;
        // Respawn clears the queued command stream below; report a clean
        // consume state so the client's lead loop doesn't read the wipe as
        // starvation.
        physics.last_tick_consumed_command = true;
        physics.buffered_command_count = 0;
        physics.updated_at = now;
        if let Some(mut intent) = ctx.db.player_intent().identity().find(state.player_id) {
            intent.forward = 0.0;
            intent.strafe = 0.0;
            intent.yaw = spawn_yaw;
            intent.jump = false;
            intent.input_tick = physics.last_processed_tick;
            intent.updated_at = now;
            record_table_write(TableWriteKind::PlayerIntent);
            ctx.db.player_intent().identity().update(intent);
        }
        reset_player_resources_to_full(ctx, state.player_id, now);
        reset_dodge_charge_state_to_full(ctx, state.player_id, now);
        clear_pending_player_commands(ctx, state.player_id);
    }

    true
}

/// Returns `None` when the actor is not a dummy; otherwise `Some(changed)`
/// where `changed` says whether the physics row needs a commit. Stationary
/// dummies previously rewrote (and replicated) their `PlayerPhysics` row every
/// tick just to restamp `updated_at` (tick audit T3). Dummies carry no
/// prediction-ack semantics (`last_processed_tick` never advances), so
/// skipping the no-op commit is safe; live-player commits are never gated.
fn try_tick_dummy_player(
    ctx: &ReducerContext,
    identity: Identity,
    now: Timestamp,
    physics: &mut PlayerPhysics,
    state: &crate::player_state::PlayerState,
) -> Option<bool> {
    if !state.is_dummy {
        return None;
    }

    if ctx
        .db
        .special_movement_runtime()
        .owner()
        .find(identity)
        .is_some()
    {
        return Some(false);
    }

    let flat_ground_only = uses_flat_training_collision(ctx, identity);
    let ground_y = surface_height_for_world_at_y_with_layout(
        arena_seed_for_identity(ctx, identity),
        flat_ground_only,
        physics.pos_x,
        physics.pos_z,
        physics.pos_y,
    );
    Some(settle_stationary_dummy(physics, ground_y, now))
}

/// Returns `None` when the actor is not a playground target; otherwise
/// `Some(changed)` (see `try_tick_dummy_player` for the write-gating rationale).
fn try_tick_playground_target(
    ctx: &ReducerContext,
    identity: Identity,
    now: Timestamp,
    physics: &mut PlayerPhysics,
) -> Option<bool> {
    if !is_playground_target(ctx, identity) {
        return None;
    }

    ctx.db.special_movement_runtime().owner().delete(identity);
    Some(settle_stationary_playground_target(physics, now))
}

fn stationary_pose_is_settled(physics: &PlayerPhysics) -> bool {
    physics.vel_x == 0.0 && physics.vel_y == 0.0 && physics.vel_z == 0.0 && physics.grounded
}

fn settle_stationary_playground_target(physics: &mut PlayerPhysics, now: Timestamp) -> bool {
    if stationary_pose_is_settled(physics) {
        // Already settled: skip the write — never restamp `updated_at` as the
        // only change on a per-tick row.
        return false;
    }

    physics.vel_x = 0.0;
    physics.vel_y = 0.0;
    physics.vel_z = 0.0;
    physics.grounded = true;
    physics.updated_at = now;
    true
}

fn settle_stationary_dummy(physics: &mut PlayerPhysics, ground_y: f32, now: Timestamp) -> bool {
    if physics.pos_y == ground_y && stationary_pose_is_settled(physics) {
        return false;
    }

    physics.pos_y = ground_y;
    physics.vel_x = 0.0;
    physics.vel_y = 0.0;
    physics.vel_z = 0.0;
    physics.grounded = true;
    physics.updated_at = now;
    true
}

#[allow(clippy::too_many_arguments)]
fn simulate_non_dummy_player_kinematics(
    identity: Identity,
    physics: &mut PlayerPhysics,
    intent: &PlayerIntent,
    arena_seed: Option<u64>,
    flat_ground_only: bool,
    open_world_scene_name: String,
    now: Timestamp,
    dt: f32,
    movement_blocked: bool,
    move_speed_multiplier: f32,
    hit_radius: f32,
    hit_height: f32,
) {
    let ground_at = |x: f32, z: f32, probe_y: f32| -> f32 {
        surface_height_for_world_at_y_with_layout_for_scene(
            arena_seed,
            flat_ground_only,
            Some(open_world_scene_name.as_str()),
            x,
            z,
            probe_y,
        )
    };

    if physics.grounded {
        // Pre-step stabilization: terrain can shift under the player between ticks.
        // We still resnap after integration for final authoritative placement.
        physics.pos_y = ground_at(physics.pos_x, physics.pos_z, physics.pos_y);
    }

    // === Step 1: Always update yaw from intent ===
    // Player can rotate regardless of grounded state
    physics.yaw = intent.yaw;

    // === Step 2: Branch on grounded state ===
    if physics.grounded {
        // --- GROUNDED BRANCH ---
        if !movement_blocked {
            // Compute velocity from intent
            let (vel_x, vel_z) = velocity_from_intent(
                intent.forward,
                intent.strafe,
                intent.yaw,
                MOVE_SPEED * move_speed_multiplier,
            );
            physics.vel_x = vel_x;
            physics.vel_z = vel_z;
        }
        physics.vel_y = 0.0; // No vertical velocity when grounded

        // Check for jump request
        if intent.jump && !movement_blocked {
            // === JUMP TRANSITION ===
            // This is the ONLY place grounded becomes false
            log::debug!(
                "[JUMP] Player {} | pos_y={:.2} | vel=({:.2},{:.2},{:.2}) | grounded: true -> false",
                &identity.to_hex()[..8],
                physics.pos_y,
                physics.vel_x,
                physics.vel_y,
                physics.vel_z
            );

            physics.grounded = false;
            physics.vel_y = JUMP_VELOCITY;

            // Horizontal velocity is already set from intent above.
            // It will be LOCKED (not overwritten) while airborne.
            // No separate preserved_vel field needed.
        }
    } else {
        // --- AIRBORNE BRANCH ---

        // Horizontal velocity is LOCKED - do not modify vel_x or vel_z
        // This is the "preservation" - we simply don't touch them.

        // Apply gravity to vertical velocity
        physics.vel_y += GRAVITY * dt;
    }

    if movement_blocked {
        // Root is an immediate horizontal stop, including while airborne.
        physics.vel_x = 0.0;
        physics.vel_z = 0.0;
    }

    // === Step 3: Integrate position ===
    // This happens regardless of grounded state.
    // CRITICAL: This happens in the SAME tick as jump transition.
    let delta_x = physics.vel_x * dt;
    let delta_z = physics.vel_z * dt;
    let max_delta = delta_x.abs().max(delta_z.abs());
    let step_count = ((max_delta / MAX_HORIZONTAL_COLLISION_STEP).ceil() as usize).max(1);
    let step_x = delta_x / step_count as f32;
    let step_z = delta_z / step_count as f32;
    let mut next_x = physics.pos_x;
    let mut next_z = physics.pos_z;

    for _ in 0..step_count {
        let target_x = next_x + step_x;
        let target_z = next_z + step_z;
        let (resolved_x, resolved_z) =
            resolve_world_horizontal_sweep_collision_y_with_layout_for_scene(
                arena_seed,
                flat_ground_only,
                Some(open_world_scene_name.as_str()),
                next_x,
                next_z,
                target_x,
                target_z,
                hit_radius.max(0.1),
                hit_height.max(0.5),
                physics.pos_y,
            );
        next_x = resolved_x;
        next_z = resolved_z;
    }

    physics.pos_x = next_x;
    physics.pos_z = next_z;

    if physics.grounded {
        let ground_y = ground_at(physics.pos_x, physics.pos_z, physics.pos_y);
        let drop_to_ground = physics.pos_y - ground_y;
        if drop_to_ground <= MAX_GROUNDED_SNAP_DOWN {
            // Small step-down or incline change: keep grounded and snap.
            physics.pos_y = ground_y;
        } else {
            // Walking off a ledge: transition to airborne instead of teleporting down.
            // We intentionally defer landing checks until the next fully-airborne frame.
            physics.grounded = false;
            physics.vel_y = GRAVITY * dt;
            physics.pos_y += physics.vel_y * dt;
        }
    } else {
        // Capture the pre-integration height so landing probes can detect crossing this frame.
        let previous_y = physics.pos_y;
        physics.pos_y += physics.vel_y * dt;
        let ground_y = ground_at(physics.pos_x, physics.pos_z, previous_y);

        // === Step 4: Check landing (ONLY if airborne) ===
        // Landing condition: crossed below sampled walkable surface AND descending.
        // We probe with previous_y so high-speed falls cannot skip narrow tops.
        // Both conditions required - prevents landing while ascending.
        // This check happens AFTER integration - player has moved.
        if physics.pos_y <= ground_y && physics.vel_y <= 0.0 {
            // === LANDING TRANSITION ===
            // This is the ONLY place grounded becomes true (after initial spawn)
            log::debug!(
                "[LAND] Player {} | pos_y={:.2} | vel_y={:.2} | grounded: false -> true",
                &identity.to_hex()[..8],
                physics.pos_y,
                physics.vel_y
            );

            physics.pos_y = ground_y; // Snap to sampled ground
            physics.vel_y = 0.0; // Stop falling
            physics.grounded = true;

            // Note: vel_x and vel_z retain their values from airtime.
            // Next tick (grounded), they'll be recomputed from intent.
            // This prevents stale velocity issues.
        }
    }

    physics.updated_at = now;
}

fn uses_flat_training_collision(ctx: &ReducerContext, identity: Identity) -> bool {
    let Some(world) = ctx.db.player_world().identity().find(identity) else {
        return false;
    };

    let Some(instance_id) = world.instance_id else {
        return false;
    };

    is_training_instance(ctx, instance_id)
}

fn sync_player_movement_context(
    state: &mut crate::player_state::PlayerState,
    movement_blocked: bool,
    move_speed_multiplier: f32,
    movement_context_tick: u32,
) -> bool {
    let clamped_multiplier = move_speed_multiplier.clamp(0.0, 4.0);
    let multiplier_changed = (state.move_speed_multiplier - clamped_multiplier).abs() > 0.0001;
    let changed = state.movement_blocked != movement_blocked
        || multiplier_changed
        || state.movement_context_tick != movement_context_tick;

    if !changed {
        return false;
    }

    state.movement_blocked = movement_blocked;
    state.move_speed_multiplier = clamped_multiplier;
    state.movement_context_tick = movement_context_tick;
    true
}

fn sync_player_voluntary_move_epoch(
    state: &mut crate::player_state::PlayerState,
    movement_blocked: bool,
    intent: &PlayerIntent,
    grounded_before_step: bool,
    command_input_tick: Option<u32>,
) -> bool {
    if movement_blocked {
        return false;
    }

    // Axis input is voluntary even if some other force also moves the player.
    // Jump only counts when the server could accept it from a grounded step.
    let accepted_move = intent.forward.abs() > ZERO_INPUT_EPSILON
        || intent.strafe.abs() > ZERO_INPUT_EPSILON
        || (intent.jump && grounded_before_step);
    if !accepted_move {
        return false;
    }

    state.voluntary_move_epoch = state.voluntary_move_epoch.saturating_add(1);
    if let Some(command_input_tick) = command_input_tick {
        state.last_voluntary_move_input_tick = command_input_tick;
    }
    true
}

fn tick_special_movement_runtimes(ctx: &ReducerContext, now: Timestamp) {
    let runtimes: Vec<crate::spells::SpecialMovementRuntime> =
        ctx.db.special_movement_runtime().iter().collect();
    for runtime in runtimes {
        if is_playground_target(ctx, runtime.owner) {
            ctx.db
                .special_movement_runtime()
                .owner()
                .delete(runtime.owner);
            continue;
        }

        let Some(mut physics) = ctx.db.player_physics().identity().find(runtime.owner) else {
            ctx.db
                .special_movement_runtime()
                .owner()
                .delete(runtime.owner);
            continue;
        };
        let Some(state) = ctx.db.player_state().player_id().find(runtime.owner) else {
            ctx.db
                .special_movement_runtime()
                .owner()
                .delete(runtime.owner);
            continue;
        };
        if !state.alive {
            ctx.db
                .special_movement_runtime()
                .owner()
                .delete(runtime.owner);
            continue;
        }

        let (desired_x, desired_y, desired_z, desired_yaw, finished) =
            sample_special_movement_pose(&runtime, now);
        let arena_seed = arena_seed_for_identity(ctx, runtime.owner);
        let flat_ground_only = uses_flat_training_collision(ctx, runtime.owner);
        let ground_y = surface_height_for_world_at_y_with_layout(
            arena_seed,
            flat_ground_only,
            desired_x,
            desired_z,
            desired_y,
        );
        let resolved_y = resolve_special_movement_y(
            &runtime.collision_policy,
            runtime.start_y,
            desired_y,
            ground_y,
        );

        let prev_x = physics.pos_x;
        let prev_y = physics.pos_y;
        let prev_z = physics.pos_z;
        physics.pos_x = desired_x;
        physics.pos_y = resolved_y;
        physics.pos_z = desired_z;
        physics.yaw = desired_yaw;
        if finished {
            // Prevent residual authored-movement velocity from carrying into
            // normal physics (airborne lock would otherwise slide the player
            // past the destination). Grounded state is handed back to normal
            // physics instead of being reclassified from terrain here.
            physics.vel_x = 0.0;
            physics.vel_y = 0.0;
            physics.vel_z = 0.0;
        } else {
            physics.vel_x = (desired_x - prev_x) / FIXED_TICK_SECONDS;
            physics.vel_y = (resolved_y - prev_y) / FIXED_TICK_SECONDS;
            physics.vel_z = (desired_z - prev_z) / FIXED_TICK_SECONDS;
        }
        physics.grounded =
            special_movement_grounded_state(&runtime.collision_policy, physics.grounded);
        physics.updated_at = now;
        let handoff_input_tick = physics.last_processed_tick;
        let handoff_yaw = physics.yaw;
        commit_player_physics(
            ctx,
            physics,
            PhysicsWriteMode::SpecialMovementTick,
            "tick_special_movement_runtimes",
        );

        if finished {
            ctx.db
                .special_movement_runtime()
                .owner()
                .delete(runtime.owner);
            reset_player_intent_after_special_movement(
                ctx,
                runtime.owner,
                handoff_input_tick,
                handoff_yaw,
                now,
            );
            // Drop queued commands and advance the receive cursor through the
            // normal client lead window. Commands authored during the special
            // movement can arrive after this reducer tick; rejecting that
            // in-flight window prevents a delayed jump edge from launching on
            // the first post-special-movement physics ticks.
            clear_pending_player_commands_through_tick(
                ctx,
                runtime.owner,
                handoff_input_tick.saturating_add(SPECIAL_MOVEMENT_INPUT_DISCARD_LEAD_TICKS),
            );
        }
    }
}

fn reset_player_intent_after_special_movement(
    ctx: &ReducerContext,
    identity: Identity,
    input_tick: u32,
    yaw: f32,
    now: Timestamp,
) {
    let Some(mut intent) = ctx.db.player_intent().identity().find(identity) else {
        return;
    };

    intent.forward = 0.0;
    intent.strafe = 0.0;
    intent.yaw = yaw;
    intent.jump = false;
    intent.input_tick = input_tick;
    intent.updated_at = now;
    record_table_write(TableWriteKind::PlayerIntent);
    ctx.db.player_intent().identity().update(intent);
}

fn special_movement_grounded_state(collision_policy: &str, current_grounded: bool) -> bool {
    if uses_fixed_y_collision_policy(collision_policy) {
        false
    } else {
        current_grounded
    }
}

fn sample_special_movement_pose(
    runtime: &crate::spells::SpecialMovementRuntime,
    now: Timestamp,
) -> (f32, f32, f32, f32, bool) {
    let start = runtime.started_at.to_micros_since_unix_epoch();
    let duration_micros = (runtime.duration_ms as i64).saturating_mul(1000);
    let end = start.saturating_add(duration_micros);
    let now_micros = now.to_micros_since_unix_epoch();
    let finished = runtime.duration_ms == 0 || now_micros >= end;

    if runtime.path_mode == SPECIAL_MOVEMENT_PATH_INSTANT || runtime.duration_ms == 0 {
        return (
            runtime.end_x,
            runtime.end_y,
            runtime.end_z,
            runtime.facing_yaw_start,
            true,
        );
    }

    let progress = if duration_micros <= 0 {
        1.0
    } else {
        ((now_micros - start) as f64 / duration_micros as f64).clamp(0.0, 1.0) as f32
    };
    let pos_x = runtime.start_x + (runtime.end_x - runtime.start_x) * progress;
    let pos_y = if uses_fixed_y_collision_policy(&runtime.collision_policy) {
        runtime.start_y
    } else {
        runtime.start_y + (runtime.end_y - runtime.start_y) * progress
    };
    let pos_z = runtime.start_z + (runtime.end_z - runtime.start_z) * progress;
    let yaw = if runtime.facing_policy == SPECIAL_MOVEMENT_FACING_FACE_PATH {
        let dx = runtime.end_x - runtime.start_x;
        let dz = runtime.end_z - runtime.start_z;
        if dx * dx + dz * dz > 0.0001 {
            dx.atan2(dz)
        } else {
            runtime.facing_yaw_start
        }
    } else {
        runtime.facing_yaw_start
    };

    (pos_x, pos_y, pos_z, yaw, finished)
}

fn uses_fixed_y_collision_policy(collision_policy: &str) -> bool {
    collision_policy == SPECIAL_MOVEMENT_COLLISION_STOP_AT_BLOCK_FIXED_Y
        || collision_policy == SPECIAL_MOVEMENT_COLLISION_STOP_AT_BLOCK_KEEP_HEIGHT_LEGACY
}

/// Synchronizes the persistent fallback state used when the next queued input
/// command has not arrived. Tick/timestamp bookkeeping alone is intentionally
/// excluded: the every-tick acknowledgement lives on `PlayerPhysics`, while
/// `PlayerIntent` only needs a write when gameplay-observable retained input
/// changes. Jump edges remain queue-only and are never retained here.
fn apply_player_intent_fallback_if_changed(
    current: &mut PlayerIntent,
    applied: &PlayerIntent,
) -> bool {
    let changed = current.forward != applied.forward
        || current.strafe != applied.strafe
        || current.yaw != applied.yaw
        || current.jump;
    if !changed {
        return false;
    }

    current.forward = applied.forward;
    current.strafe = applied.strafe;
    current.yaw = applied.yaw;
    current.jump = false;
    current.input_tick = applied.input_tick;
    current.updated_at = applied.updated_at;
    true
}

fn try_tick_special_movement_player(
    ctx: &ReducerContext,
    identity: Identity,
    now: Timestamp,
    movement_blocked: bool,
    move_speed_multiplier: f32,
    physics: &mut PlayerPhysics,
    state: &mut crate::player_state::PlayerState,
    intent: &mut PlayerIntent,
) -> bool {
    if ctx
        .db
        .special_movement_runtime()
        .owner()
        .find(identity)
        .is_none()
    {
        return false;
    }

    let next_input_tick = physics.last_processed_tick.saturating_add(1);
    let mut step_intent = PlayerIntent {
        identity,
        forward: intent.forward,
        strafe: intent.strafe,
        yaw: intent.yaw,
        jump: false,
        input_tick: next_input_tick,
        updated_at: now,
    };
    let mut consumed_real_command = false;
    if let Some(command) = pop_command_for_tick(ctx, identity, next_input_tick) {
        step_intent.forward = command.forward;
        step_intent.strafe = command.strafe;
        step_intent.yaw = command.yaw;
        consumed_real_command = true;
    }

    physics.last_processed_tick = next_input_tick;
    physics.last_tick_consumed_command = consumed_real_command;
    physics.buffered_command_count = count_buffered_commands(ctx, identity);
    physics.updated_at = now;
    if apply_player_intent_fallback_if_changed(intent, &step_intent) {
        record_table_write(TableWriteKind::PlayerIntent);
        ctx.db.player_intent().identity().update(PlayerIntent {
            identity: intent.identity,
            forward: intent.forward,
            strafe: intent.strafe,
            yaw: intent.yaw,
            jump: intent.jump,
            input_tick: intent.input_tick,
            updated_at: intent.updated_at,
        });
    }

    let state_changed = sync_player_movement_context(
        state,
        movement_blocked,
        move_speed_multiplier,
        next_input_tick,
    );
    commit_player_physics(
        ctx,
        PlayerPhysics {
            identity: physics.identity,
            pos_x: physics.pos_x,
            pos_y: physics.pos_y,
            pos_z: physics.pos_z,
            vel_x: physics.vel_x,
            vel_y: physics.vel_y,
            vel_z: physics.vel_z,
            yaw: physics.yaw,
            grounded: physics.grounded,
            last_processed_tick: physics.last_processed_tick,
            last_tick_consumed_command: physics.last_tick_consumed_command,
            buffered_command_count: physics.buffered_command_count,
            updated_at: physics.updated_at,
        },
        PhysicsWriteMode::Normal,
        "try_tick_special_movement_player",
    );
    if state_changed {
        ctx.db
            .player_state()
            .player_id()
            .update(crate::player_state::PlayerState {
                player_id: state.player_id,
                is_dummy: state.is_dummy,
                alive: state.alive,
                eliminated: state.eliminated,
                hp: state.hp,
                max_hp: state.max_hp,
                hit_radius: state.hit_radius,
                hit_height: state.hit_height,
                movement_blocked: state.movement_blocked,
                move_speed_multiplier: state.move_speed_multiplier,
                movement_context_tick: state.movement_context_tick,
                voluntary_move_epoch: state.voluntary_move_epoch,
                last_voluntary_move_input_tick: state.last_voluntary_move_input_tick,
                respawn_at: state.respawn_at,
                last_strike_id: state.last_strike_id.clone(),
                last_strike_at: state.last_strike_at,
            });
    }

    true
}

fn tick_player(
    ctx: &ReducerContext,
    identity: Identity,
    now: Timestamp,
    dt: f32,
    movement_modifiers: &MovementModifiers,
    temporary_modifiers: &TemporaryCombatModifiers,
    contexts: &PlayerTickContexts,
) {
    // Get current physics state
    let Some(mut physics) = ctx.db.player_physics().identity().find(identity) else {
        return;
    };

    // Get current player state
    let Some(mut state) = ctx.db.player_state().player_id().find(identity) else {
        return;
    };

    let next_input_tick = physics.last_processed_tick.saturating_add(1);
    let movement_blocked = movement_modifiers.blocks_movement(&identity);
    let mut move_speed_multiplier =
        movement_modifiers.move_speed_multiplier(&identity, next_input_tick);

    // Dead players ignore inputs and physics until respawn.
    if try_tick_dead_player(ctx, now, &mut physics, &mut state) {
        if state.alive {
            commit_player_physics(
                ctx,
                physics,
                PhysicsWriteMode::Force,
                "try_tick_dead_player_respawn",
            );
            ctx.db.player_state().player_id().update(state);
        }
        return;
    }

    if let Some(physics_changed) = try_tick_playground_target(ctx, identity, now, &mut physics) {
        if physics_changed {
            commit_player_physics(
                ctx,
                physics,
                PhysicsWriteMode::Normal,
                "try_tick_playground_target",
            );
        }
        return;
    }

    if let Some(physics_changed) = try_tick_dummy_player(ctx, identity, now, &mut physics, &state) {
        let movement_context_tick = physics.last_processed_tick;
        let state_changed = sync_player_movement_context(
            &mut state,
            movement_blocked,
            move_speed_multiplier,
            movement_context_tick,
        );
        if physics_changed {
            commit_player_physics(
                ctx,
                physics,
                PhysicsWriteMode::Normal,
                "try_tick_dummy_player",
            );
        }
        if state_changed {
            ctx.db.player_state().player_id().update(state);
        }
        return;
    }

    // Get current intent
    let Some(mut intent) = ctx.db.player_intent().identity().find(identity) else {
        return;
    };
    if try_tick_special_movement_player(
        ctx,
        identity,
        now,
        movement_blocked,
        move_speed_multiplier,
        &mut physics,
        &mut state,
        &mut intent,
    ) {
        return;
    }
    let mut step_intent = PlayerIntent {
        identity,
        forward: intent.forward,
        strafe: intent.strafe,
        yaw: intent.yaw,
        jump: false,
        input_tick: next_input_tick,
        updated_at: now,
    };
    let mut applied_command_input_tick = None;
    if let Some(command) = pop_command_for_tick(ctx, identity, next_input_tick) {
        step_intent.forward = command.forward;
        step_intent.strafe = command.strafe;
        step_intent.yaw = command.yaw;
        step_intent.jump = command.jump;
        step_intent.input_tick = next_input_tick;
        step_intent.updated_at = now;
        applied_command_input_tick = Some(command.input_tick);
    } else {
        // Command hasn't arrived yet — use latest known intent values.
        // The client's prediction deadband absorbs the small error from
        // the stale yaw. Always advance the tick so the server stays
        // current and spells/effects use an up-to-date position.
        log::debug!(
            "[MOVE_FALLBACK] Player {} | tick={} | using fallback intent from tick={}",
            &identity.to_hex()[..8],
            next_input_tick,
            intent.input_tick
        );
        crate::tick_metrics::record_move_fallback();
        step_intent.jump = false;
        step_intent.input_tick = next_input_tick;
        step_intent.updated_at = now;
    }

    // S5: publish this tick's consume truth beside the ack so the client's
    // lead control loop sees starvation/surplus instead of guessing.
    physics.last_tick_consumed_command = applied_command_input_tick.is_some();
    physics.buffered_command_count = count_buffered_commands(ctx, identity);

    let equipment = contexts.equipment(ctx, identity);
    move_speed_multiplier *= contexts.derived(ctx, identity).run_speed_multiplier;
    move_speed_multiplier *= equipment.move_speed_multiplier();

    let grounded_before_step = physics.grounded;
    simulate_non_dummy_player_kinematics(
        identity,
        &mut physics,
        &step_intent,
        arena_seed_for_identity(ctx, identity),
        uses_flat_training_collision(ctx, identity),
        open_world_scene_name_for_identity(ctx, identity),
        now,
        dt,
        movement_blocked,
        move_speed_multiplier,
        state.hit_radius,
        state.hit_height,
    );
    physics.last_processed_tick = next_input_tick;
    if apply_player_intent_fallback_if_changed(&mut intent, &step_intent) {
        record_table_write(TableWriteKind::PlayerIntent);
        ctx.db.player_intent().identity().update(intent);
    }
    let resource_inputs = ResourceSpecInputs {
        status_modifiers: temporary_modifiers,
        equipment: &equipment,
    };
    tick_primary_resource_for_player(ctx, identity, now, dt, &resource_inputs);
    let voluntary_epoch_changed = sync_player_voluntary_move_epoch(
        &mut state,
        movement_blocked,
        &step_intent,
        grounded_before_step,
        applied_command_input_tick,
    );
    let state_changed = sync_player_movement_context(
        &mut state,
        movement_blocked,
        move_speed_multiplier,
        next_input_tick,
    ) || voluntary_epoch_changed;

    // === Step 5: Write physics state ===
    commit_player_physics(
        ctx,
        physics,
        PhysicsWriteMode::Normal,
        "simulate_non_dummy_player_kinematics",
    );
    if state_changed {
        ctx.db.player_state().player_id().update(state);
    }
}

/// The game tick - runs every 33ms.
///
/// This is the SOLE AUTHORITY on physics state.
///
/// The reducer is intentionally a phase orchestrator:
/// 1. Pre-tick housekeeping (casts, practice, queued combat/effects)
/// 2. Per-player authoritative simulation
/// 3. Post-tick pruning/maintenance
///
/// Physics ownership remains singular:
/// - `game_tick` is the only reducer that writes `PlayerPhysics`
/// - helpers may structure the logic, but they execute only inside this reducer
#[reducer]
pub fn game_tick(ctx: &ReducerContext, timer: GameLoopTimer) -> Result<(), String> {
    // Fixed-rate chain first: the next link commits with this tick's writes.
    // (A returned Err would roll the link back too — the watchdog re-seeds
    // that case within a second.)
    reschedule_game_tick(ctx, &timer);
    // Existing DBs republish without re-running init; seed the watchdog here.
    ensure_game_loop_watchdog_schedule(ctx);

    let dt = FIXED_TICK_SECONDS;
    let now = ctx.timestamp;
    let profiling_enabled = tick_profiling_enabled();
    // In the wasm module, one tick per profile window is timed with host-side
    // console timers (`ScopeTimer` reads zero there — no `Instant` on wasm).
    let stopwatch_active =
        profiling_enabled && crate::tick_metrics::take_stopwatch_sample_request();
    let _total_stopwatch = PhaseStopwatch::start(stopwatch_active, "tick_profile/total");
    let total_timer = ScopeTimer::start(profiling_enabled);

    // Per-tick, per-player equipment/derived memo (tick audit T2), shared by
    // the pre-tick and player-simulation phases.
    let player_contexts = PlayerTickContexts::collect(ctx);

    let pre_tick_stopwatch = PhaseStopwatch::start(stopwatch_active, "tick_profile/pre_tick");
    let pre_tick_timer = ScopeTimer::start(profiling_enabled);
    let mut pre_subphase_micros = [0u32; PRE_TICK_SUBPHASE_COUNT];
    let (movement_modifiers, temporary_modifiers) = run_pre_tick_housekeeping_phase(
        ctx,
        now,
        dt,
        profiling_enabled,
        stopwatch_active,
        &mut pre_subphase_micros,
        &player_contexts,
    )?;
    let pre_tick_micros = pre_tick_timer.elapsed_micros();
    drop(pre_tick_stopwatch);

    let player_sim_stopwatch = PhaseStopwatch::start(stopwatch_active, "tick_profile/player_sim");
    let player_sim_timer = ScopeTimer::start(profiling_enabled);
    run_player_simulation_phase(
        ctx,
        now,
        dt,
        &movement_modifiers,
        &temporary_modifiers,
        &player_contexts,
    );
    resolve_pending_casts(ctx, now)?;
    let player_sim_micros = player_sim_timer.elapsed_micros();
    drop(player_sim_stopwatch);

    let post_tick_stopwatch = PhaseStopwatch::start(stopwatch_active, "tick_profile/post_tick");
    let post_tick_timer = ScopeTimer::start(profiling_enabled);
    run_post_tick_maintenance_phase(ctx, now);
    let post_tick_micros = post_tick_timer.elapsed_micros();
    drop(post_tick_stopwatch);

    let match_stopwatch = PhaseStopwatch::start(stopwatch_active, "tick_profile/match");
    let match_maintenance_timer = ScopeTimer::start(profiling_enabled);
    run_match_world_maintenance_phase(ctx, now);
    let match_maintenance_micros = match_maintenance_timer.elapsed_micros();
    drop(match_stopwatch);

    if profiling_enabled {
        let maybe_window_ticks = record_tick_profile(
            now,
            TickProfileSample {
                total_micros: total_timer.elapsed_micros(),
                pre_tick_micros,
                player_sim_micros,
                post_tick_micros,
                match_maintenance_micros,
                pre_subphase_micros,
            },
        );
        if let Some(window_ticks) = maybe_window_ticks {
            log_tick_scan_profile(ctx, window_ticks);
            crate::tick_metrics::request_stopwatch_sample();
        }
    }

    Ok(())
}

const COUNTDOWN_DURATION: Duration = Duration::from_secs(3);

fn tick_countdowns(ctx: &ReducerContext, now: Timestamp) {
    let instances: Vec<_> = ctx
        .db
        .arena_instance()
        .iter()
        .filter(|a| a.phase == MATCH_PHASE_COUNTDOWN)
        .collect();

    for mut arena in instances {
        let Some(started_at) = arena.countdown_started_at else {
            continue;
        };
        let now_micros: i64 = now.to_micros_since_unix_epoch();
        let started_micros: i64 = started_at.to_micros_since_unix_epoch();
        let elapsed_micros = now_micros.saturating_sub(started_micros);
        if elapsed_micros >= COUNTDOWN_DURATION.as_micros() as i64 {
            arena.phase = MATCH_PHASE_IN_PROGRESS.to_string();
            arena.countdown_started_at = None;
            ctx.db.arena_instance().id().update(arena);
        }
    }
}

