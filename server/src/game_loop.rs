/// Schedule table for the game loop.
/// Inserting a row schedules game_tick to run. Rows are one-shot Time links
/// in a fixed-rate chain (see reschedule_game_tick); the watchdog re-seeds
/// the chain if it ever dies.
#[table(accessor = game_loop_timer, scheduled(game_tick))]
pub struct GameLoopTimer {
    #[primary_key]
    #[auto_inc]
    pub scheduled_id: u64,
    pub scheduled_at: ScheduleAt,
}

/// Immortal (host-managed Interval) backstop for the fixed-rate chain: a
/// panicked or rolled-back game_tick can remove the next link, while a module
/// publish can leave an overdue row present but inert. This runs at 1 Hz,
/// reads one tiny table, and replaces either failure state.
#[table(accessor = game_loop_watchdog, scheduled(game_loop_watchdog_tick))]
pub struct GameLoopWatchdog {
    #[primary_key]
    #[auto_inc]
    pub scheduled_id: u64,
    pub scheduled_at: ScheduleAt,
}

#[reducer]
pub fn game_loop_watchdog_tick(
    ctx: &ReducerContext,
    _timer: GameLoopWatchdog,
) -> Result<(), String> {
    let overdue_ids: Vec<u64> = ctx
        .db
        .game_loop_timer()
        .iter()
        .filter(|row| game_loop_timer_is_overdue(ctx.timestamp, &row.scheduled_at))
        .map(|row| row.scheduled_id)
        .collect();
    for scheduled_id in &overdue_ids {
        ctx.db
            .game_loop_timer()
            .scheduled_id()
            .delete(*scheduled_id);
    }

    if ctx.db.game_loop_timer().iter().next().is_none() {
        log::warn!(
            "[GAME_LOOP] watchdog re-seeding a dead game_tick chain overdue_rows={}",
            overdue_ids.len()
        );
        ctx.db.game_loop_timer().insert(GameLoopTimer {
            scheduled_id: 0,
            scheduled_at: ScheduleAt::Time(fresh_game_tick_schedule(ctx.timestamp)),
        });
    }
    Ok(())
}

/// Module initialization - starts the game loop.
#[reducer(init)]
pub fn init(ctx: &ReducerContext) -> Result<(), String> {
    ensure_game_loop_schedule(ctx);
    ensure_game_loop_watchdog_schedule(ctx);
    crate::contract_version::sync_contract_versions(ctx);
    bootstrap_server_state(ctx);
    despawn_legacy_default_dummies(ctx);

    let repaired_rows = backfill_player_world_rows(ctx);
    if repaired_rows > 0 {
        log::warn!(
            "[INIT] Backfilled {} missing player_world rows as open-world",
            repaired_rows
        );
    }
    let repaired_scene_rows = backfill_player_open_world_scene_rows(ctx);
    if repaired_scene_rows > 0 {
        log::warn!(
            "[INIT] Backfilled {} missing player_open_world_scene rows with default open-world scene",
            repaired_scene_rows
        );
    }

    log::info!("[INIT] Game loop started at 30.3Hz (33ms tick)");
    if tick_profiling_enabled() {
        if crate::tick_metrics::WALL_CLOCK_AVAILABLE {
            log::info!(
                "[INIT] Tick profiling enabled via {}. Logging 5.00s rolling stats; target p95 < 20ms, p99 < 28ms, no sustained ticks over {}ms.",
                crate::tick_metrics::TICK_PROFILE_ENV_VAR,
                FIXED_TICK_MILLIS
            );
        } else {
            log::info!(
                "[INIT] Tick profiling enabled via compile-time {} (wasm module). Logging 5.00s [TICK_PROFILE_SCAN] counter windows; wall-clock comes from tick_profile/* console timers sampled once per window.",
                crate::tick_metrics::TICK_PROFILE_ENV_VAR
            );
        }
    }
    Ok(())
}

