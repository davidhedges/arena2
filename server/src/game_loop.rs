#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct TickProfileSample {
    total_micros: u32,
    pre_tick_micros: u32,
    player_sim_micros: u32,
    post_tick_micros: u32,
    match_maintenance_micros: u32,
    pre_subphase_micros: [u32; PRE_TICK_SUBPHASE_COUNT],
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct TickPhaseSummary {
    p95_micros: u32,
    max_micros: u32,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct TickProfileSummary {
    count: usize,
    total_p50_micros: u32,
    total_p95_micros: u32,
    total_p99_micros: u32,
    total_max_micros: u32,
    over_budget_count: usize,
    max_consecutive_over_budget: usize,
    pre_tick: TickPhaseSummary,
    player_sim: TickPhaseSummary,
    post_tick: TickPhaseSummary,
    match_maintenance: TickPhaseSummary,
    pre_subphases: [TickPhaseSummary; PRE_TICK_SUBPHASE_COUNT],
}

#[derive(Default)]
struct TickProfileWindowState {
    window_started_at_micros: Option<i64>,
    total_micros: Vec<u32>,
    pre_tick_micros: Vec<u32>,
    player_sim_micros: Vec<u32>,
    post_tick_micros: Vec<u32>,
    match_maintenance_micros: Vec<u32>,
    pre_subphase_micros: [Vec<u32>; PRE_TICK_SUBPHASE_COUNT],
    over_budget_count: usize,
    consecutive_over_budget: usize,
    max_consecutive_over_budget: usize,
}

impl TickProfileWindowState {
    fn record(&mut self, now_micros: i64, sample: TickProfileSample) -> Option<TickProfileSummary> {
        if self.window_started_at_micros.is_none() {
            self.window_started_at_micros = Some(now_micros);
        }

        self.total_micros.push(sample.total_micros);
        self.pre_tick_micros.push(sample.pre_tick_micros);
        self.player_sim_micros.push(sample.player_sim_micros);
        self.post_tick_micros.push(sample.post_tick_micros);
        self.match_maintenance_micros
            .push(sample.match_maintenance_micros);
        for (values, micros) in self
            .pre_subphase_micros
            .iter_mut()
            .zip(sample.pre_subphase_micros.iter())
        {
            values.push(*micros);
        }

        if sample.total_micros > TICK_BUDGET_MICROS {
            self.over_budget_count += 1;
            self.consecutive_over_budget += 1;
            self.max_consecutive_over_budget = self
                .max_consecutive_over_budget
                .max(self.consecutive_over_budget);
        } else {
            self.consecutive_over_budget = 0;
        }

        let window_started_at_micros = self.window_started_at_micros.unwrap_or(now_micros);
        if now_micros.saturating_sub(window_started_at_micros) < TICK_PROFILE_WINDOW_MICROS {
            return None;
        }

        self.flush()
    }

    fn flush(&mut self) -> Option<TickProfileSummary> {
        if self.total_micros.is_empty() {
            self.window_started_at_micros = None;
            self.consecutive_over_budget = 0;
            return None;
        }

        let mut pre_subphases = [TickPhaseSummary::default(); PRE_TICK_SUBPHASE_COUNT];
        for (summary, values) in pre_subphases
            .iter_mut()
            .zip(self.pre_subphase_micros.iter())
        {
            *summary = summarize_phase(values);
        }

        let summary = TickProfileSummary {
            count: self.total_micros.len(),
            total_p50_micros: percentile_value(&self.total_micros, 50, 100),
            total_p95_micros: percentile_value(&self.total_micros, 95, 100),
            total_p99_micros: percentile_value(&self.total_micros, 99, 100),
            total_max_micros: max_value(&self.total_micros),
            over_budget_count: self.over_budget_count,
            max_consecutive_over_budget: self.max_consecutive_over_budget,
            pre_tick: summarize_phase(&self.pre_tick_micros),
            player_sim: summarize_phase(&self.player_sim_micros),
            post_tick: summarize_phase(&self.post_tick_micros),
            match_maintenance: summarize_phase(&self.match_maintenance_micros),
            pre_subphases,
        };

        self.window_started_at_micros = None;
        self.total_micros.clear();
        self.pre_tick_micros.clear();
        self.player_sim_micros.clear();
        self.post_tick_micros.clear();
        self.match_maintenance_micros.clear();
        for values in self.pre_subphase_micros.iter_mut() {
            values.clear();
        }
        self.over_budget_count = 0;
        self.consecutive_over_budget = 0;
        self.max_consecutive_over_budget = 0;

        Some(summary)
    }
}

fn max_value(values: &[u32]) -> u32 {
    values.iter().copied().max().unwrap_or(0)
}

fn summarize_phase(values: &[u32]) -> TickPhaseSummary {
    TickPhaseSummary {
        p95_micros: percentile_value(values, 95, 100),
        max_micros: max_value(values),
    }
}

fn percentile_value(values: &[u32], numerator: usize, denominator: usize) -> u32 {
    if values.is_empty() {
        return 0;
    }

    let mut sorted = values.to_vec();
    sorted.sort_unstable();
    percentile_sorted(&sorted, numerator, denominator)
}

fn percentile_sorted(sorted: &[u32], numerator: usize, denominator: usize) -> u32 {
    if sorted.is_empty() {
        return 0;
    }

    let rank = div_ceil(sorted.len() * numerator, denominator).saturating_sub(1);
    sorted[rank.min(sorted.len().saturating_sub(1))]
}

fn div_ceil(value: usize, divisor: usize) -> usize {
    if divisor == 0 {
        return 0;
    }
    (value + divisor - 1) / divisor
}

fn format_micros(micros: u32) -> String {
    format!("{:.2}ms", micros as f32 / 1_000.0)
}

fn tick_profile_store() -> &'static Mutex<TickProfileWindowState> {
    static TICK_PROFILE_STORE: OnceLock<Mutex<TickProfileWindowState>> = OnceLock::new();
    TICK_PROFILE_STORE.get_or_init(|| Mutex::new(TickProfileWindowState::default()))
}

/// Returns the number of ticks in the flushed window, or `None` while the
/// window is still accumulating. The tick count matters for interpretation:
/// SpacetimeDB may run several pooled wasm instances, each with its own copy
/// of this static window state, so one log line covers only the ticks that
/// executed on that instance — always read the counters as per-tick ratios
/// against `ticks=`, not as absolute per-5s totals.
fn record_tick_profile(now: Timestamp, sample: TickProfileSample) -> Option<usize> {
    let maybe_summary = {
        let mut state = tick_profile_store()
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        state.record(now.to_micros_since_unix_epoch(), sample)
    };

    let summary = maybe_summary?;

    if !crate::tick_metrics::WALL_CLOCK_AVAILABLE {
        // Percentile micros are all zero in the wasm module (no Instant);
        // wall-clock comes from the sampled console timers instead.
        return Some(summary.count);
    }

    log::info!(
        "[TICK_PROFILE] window=5.00s ticks={} total(p50/p95/p99/max)={}/{}/{}/{} over_budget={} max_consecutive_over_budget={} pre(p95/max)={}/{} player(p95/max)={}/{} post(p95/max)={}/{} match(p95/max)={}/{}",
        summary.count,
        format_micros(summary.total_p50_micros),
        format_micros(summary.total_p95_micros),
        format_micros(summary.total_p99_micros),
        format_micros(summary.total_max_micros),
        summary.over_budget_count,
        summary.max_consecutive_over_budget,
        format_micros(summary.pre_tick.p95_micros),
        format_micros(summary.pre_tick.max_micros),
        format_micros(summary.player_sim.p95_micros),
        format_micros(summary.player_sim.max_micros),
        format_micros(summary.post_tick.p95_micros),
        format_micros(summary.post_tick.max_micros),
        format_micros(summary.match_maintenance.p95_micros),
        format_micros(summary.match_maintenance.max_micros),
    );

    let mut pre_line = String::with_capacity(512);
    for (name, phase) in PRE_TICK_SUBPHASE_NAMES
        .iter()
        .zip(summary.pre_subphases.iter())
    {
        pre_line.push_str(&format!(
            " {}(p95/max)={}/{}",
            name,
            format_micros(phase.p95_micros),
            format_micros(phase.max_micros)
        ));
    }
    log::info!(
        "[TICK_PROFILE_PRE] window=5.00s ticks={}{}",
        summary.count,
        pre_line
    );

    Some(summary.count)
}

/// Log the per-window scan/write counters plus a one-shot population sample.
/// Called only when profiling is enabled and a profile window just flushed.
/// `window_ticks` is this instance's tick count for the window — divide every
/// counter by it (pooled wasm instances each report their own share).
fn log_tick_scan_profile(ctx: &ReducerContext, window_ticks: usize) {
    let scan = crate::tick_metrics::snapshot_and_reset();

    let mut alive_players = 0usize;
    let mut dummies = 0usize;
    for state in ctx.db.player_state().iter() {
        if state.is_dummy {
            dummies += 1;
        } else if state.alive {
            alive_players += 1;
        }
    }
    let alive_npcs = ctx
        .db
        .npc_state()
        .iter()
        .filter(|state| state.alive)
        .count();
    let active_statuses = ctx.db.status_effect().iter().count();
    let active_casts = ctx.db.active_cast().iter().count();
    let active_projectiles = ctx.db.active_combat_projectile().iter().count();

    let mut writes_line = String::with_capacity(256);
    for (name, count) in crate::tick_metrics::TABLE_WRITE_KIND_NAMES
        .iter()
        .zip(scan.table_writes.iter())
    {
        writes_line.push_str(&format!(" writes_{}={}", name, count));
    }

    log::info!(
        "[TICK_PROFILE_SCAN] ticks={} status_collects={} status_collect_ms={:.2} status_rows_scanned={} equipment_scans={} move_fallbacks={} npc_target_pairs={}{} alive_players={} dummies={} alive_npcs={} active_statuses={} active_casts={} active_projectiles={}",
        window_ticks,
        scan.status_collect_count,
        scan.status_collect_micros as f64 / 1_000.0,
        scan.status_collect_rows,
        scan.equipment_scan_count,
        scan.move_fallback_count,
        scan.npc_target_pairs_scanned,
        writes_line,
        alive_players,
        dummies,
        alive_npcs,
        active_statuses,
        active_casts,
        active_projectiles,
    );
}

fn timed_subphase<T>(
    profiling: bool,
    stopwatch_active: bool,
    name: &'static str,
    slot: &mut u32,
    f: impl FnOnce() -> T,
) -> T {
    if !profiling {
        return f();
    }

    let _stopwatch = PhaseStopwatch::start(stopwatch_active, name);
    let timer = ScopeTimer::start(true);
    let result = f();
    *slot = slot.saturating_add(timer.elapsed_micros());
    result
}

/// Per-tick, per-player memo of equipment totals and derived stats (tick
/// audit T2): within one tick the loadout cannot change (equip reducers run
/// outside `game_tick`), so every consumer reads the same values. Derived
/// stats may go one tick stale after a mid-tick progression change, which the
/// audit accepts. Never reused across ticks.
pub(crate) struct PlayerTickContext {
    equipment: EquipmentModifierTotals,
    derived: DerivedCombatStats,
}

pub(crate) struct PlayerTickContexts {
    by_owner: HashMap<Identity, PlayerTickContext>,
}

impl PlayerTickContexts {
    fn collect(ctx: &ReducerContext) -> Self {
        let mut by_owner = HashMap::new();
        for state in ctx.db.player_state().iter() {
            if state.is_dummy {
                continue;
            }
            let equipment = equipment_modifier_totals_for_owner(ctx, state.player_id);
            by_owner.insert(
                state.player_id,
                PlayerTickContext {
                    equipment,
                    derived: derived_combat_stats_from_allocations(
                        equipment.allocated_stat_totals(),
                    ),
                },
            );
        }
        Self { by_owner }
    }

    pub(crate) fn equipment(
        &self,
        ctx: &ReducerContext,
        owner: Identity,
    ) -> EquipmentModifierTotals {
        self.by_owner
            .get(&owner)
            .map(|context| context.equipment)
            .unwrap_or_else(|| equipment_modifier_totals_for_owner(ctx, owner))
    }

    pub(crate) fn derived(&self, ctx: &ReducerContext, owner: Identity) -> DerivedCombatStats {
        self.by_owner
            .get(&owner)
            .map(|context| context.derived)
            .unwrap_or_else(|| derived_combat_stats_for_owner(ctx, owner))
    }
}

pub(crate) fn ensure_game_loop_schedule(ctx: &ReducerContext) {
    if ctx.db.game_loop_timer().iter().next().is_some() {
        return;
    }

    // Fixed-RATE chain (S5 cadence fix): each game_tick re-inserts a one-shot
    // Time row anchored on its own scheduled time, so execution and
    // scheduling overhead do not leak into the period. The previous
    // ScheduleAt::Interval row was host-managed fixed-DELAY — measured live
    // at 36.6 ms/tick against the authored 33 ms (10% slow), which both
    // dilated the whole simulation against wall clock (dt stays 33 ms) and
    // fed the client input loop a permanent surplus.
    ctx.db.game_loop_timer().insert(GameLoopTimer {
        scheduled_id: 0,
        scheduled_at: ScheduleAt::Time(fresh_game_tick_schedule(ctx.timestamp)),
    });
    log::info!("[GAME_LOOP] Scheduled game_tick fixed-rate chain (33ms tick)");
}

pub(crate) fn ensure_game_loop_watchdog_schedule(ctx: &ReducerContext) {
    if ctx.db.game_loop_watchdog().iter().next().is_some() {
        return;
    }

    ctx.db.game_loop_watchdog().insert(GameLoopWatchdog {
        scheduled_id: 0,
        scheduled_at: ScheduleAt::Interval(GAME_LOOP_WATCHDOG_INTERVAL.into()),
    });
}

/// Re-arms the fixed-rate chain. Called FIRST inside game_tick so the next
/// link exists in the same transaction as the tick's writes.
///
/// Anchor policy: next = this row's scheduled time + one tick — never
/// "now + one tick" — so per-tick overhead cannot accumulate into the
/// period. Brief stalls are caught up (the host fires overdue rows
/// immediately); a stall deeper than the catch-up cap drops the backlog and
/// re-anchors one tick into the future instead of leaving a due-now recovery
/// row that may remain inert after a module publish.
fn fresh_game_tick_schedule(now: Timestamp) -> Timestamp {
    let tick_micros = GAME_TICK_INTERVAL.as_micros() as i64;
    Timestamp::from_micros_since_unix_epoch(
        now.to_micros_since_unix_epoch().saturating_add(tick_micros),
    )
}

fn next_game_tick_schedule(now: Timestamp, fired_at: &ScheduleAt) -> (Timestamp, bool) {
    let now_micros = now.to_micros_since_unix_epoch();
    let tick_micros = GAME_TICK_INTERVAL.as_micros() as i64;
    let anchor_micros = match fired_at {
        ScheduleAt::Time(scheduled) => scheduled.to_micros_since_unix_epoch(),
        // Legacy Interval row (pre-fix DB) has no scheduled-time anchor.
        ScheduleAt::Interval(_) => now_micros,
    };

    let anchored_next_micros = anchor_micros.saturating_add(tick_micros);
    let max_backlog_micros = tick_micros * GAME_TICK_MAX_CATCHUP_TICKS;
    let reanchored = anchored_next_micros < now_micros.saturating_sub(max_backlog_micros);
    let next_micros = if reanchored {
        // A recovery link must be strictly future-dated. Re-inserting a Time
        // row at the current reducer timestamp can leave an inert, overdue row
        // behind after a data-preserving module publish.
        now_micros.saturating_add(tick_micros)
    } else {
        anchored_next_micros
    };

    (
        Timestamp::from_micros_since_unix_epoch(next_micros),
        reanchored,
    )
}

fn game_loop_timer_is_overdue(now: Timestamp, scheduled_at: &ScheduleAt) -> bool {
    let ScheduleAt::Time(scheduled) = scheduled_at else {
        return false;
    };

    let tick_micros = GAME_TICK_INTERVAL.as_micros() as i64;
    let max_backlog_micros = tick_micros * GAME_TICK_MAX_CATCHUP_TICKS;
    scheduled.to_micros_since_unix_epoch()
        < now
            .to_micros_since_unix_epoch()
            .saturating_sub(max_backlog_micros)
}

fn reschedule_game_tick(ctx: &ReducerContext, fired: &GameLoopTimer) {
    // Defensive sweep: clears the fired row regardless of host one-shot
    // delete semantics, and migrates the legacy Interval row on first fire
    // after republish (two live rows would double-tick).
    let stale_ids: Vec<u64> = ctx
        .db
        .game_loop_timer()
        .iter()
        .map(|row| row.scheduled_id)
        .collect();
    for scheduled_id in stale_ids {
        ctx.db.game_loop_timer().scheduled_id().delete(scheduled_id);
    }

    let (next_scheduled_at, reanchored) =
        next_game_tick_schedule(ctx.timestamp, &fired.scheduled_at);
    if reanchored {
        log::warn!(
            "[GAME_LOOP] tick chain fell behind; re-anchoring one tick in the future (backlog dropped)"
        );
    }

    ctx.db.game_loop_timer().insert(GameLoopTimer {
        scheduled_id: 0,
        scheduled_at: ScheduleAt::Time(next_scheduled_at),
    });
}

